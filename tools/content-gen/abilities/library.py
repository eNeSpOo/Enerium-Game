def src_row(school, name, typ=None):
    rows = [a for a in SRC["abilities"]
            if a["Элемент"] == school and a["Название"] == name and (typ is None or a["Тип"] == typ)]
    assert len(rows) == 1, (school, name, typ, len(rows))
    return rows[0]


def T(school, name, typ=None, **kw):
    """Способность из таблицы автора. Шанс — из цены, длительность — из столбца «Длительность», × 0,6."""
    row = src_row(school, name, typ)
    price = row["Цена в атаках"]
    if "ch" not in kw and price.isdigit():
        kw["ch"] = CH_BY_PRICE[int(price)]
    m = re.match(r"\s*(\d+)", row["Длительность"] or "")
    if m:
        if "then" in kw and "left" not in kw["then"]:
            kw["then"]["left"] = rounds_of(int(m.group(1)))
        elif kw.get("kind") in LASTING and "left" not in kw:
            kw["left"] = rounds_of(int(m.group(1)))
    kw["src"] = {"no": int(row["№"]), "price": price, "dur": row["Длительность"], "coef": row["Коэффициент"], "text": row["Эффект"].strip()}
    return dict(n=name, **kw)


def N(name, **kw):
    """Новая способность — дополнение роли. Имя — заглушка."""
    return dict(n=name, **kw)


def main_dmg(tier, **kw):
    return dict(kind="dmg", stat="main", coef={1: 150, 2: 250, 3: 400}[tier], ch=TIER_CH[tier], tgt="threat", **kw)


def main_heal(tier, **kw):
    return dict(kind="heal", stat="main", coef={1: 150, 2: 250, 3: 400}[tier], ch=TIER_CH[tier], tgt="ally_lowest", **kw)


