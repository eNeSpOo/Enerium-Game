    emit(OUT_JSON, json.dumps(lib, ensure_ascii=False, indent=1) + "\n")
    write_md(lib, every)
    write_ui(lib, every)
    by = {}
    for x in every:
        k = ("ульт-сочетаний" if x.get("ult") else "сочетаний") if x.get("combo") else "ульт" if x.get("ult") else \
            {"passive": "пассивок", "reaction": "реакций", "farmPassive": "фарм-пассивок", "farm": "фарм-активок"}.get(x["kind"], "активных")
        by[k] = by.get(k, 0) + 1
    head = f"Способностей {len(every)}: " + ", ".join(f"{k} {v}" for k, v in by.items())
    if CHECK:
        print(head + "; законы сочетаний Б1–Б5 и описаний О1–О4 держатся.")
