# ---------------- сборка ----------------
def plural(n, one, few, many):
    n10, n100 = abs(n) % 10, abs(n) % 100
    if n10 == 1 and n100 != 11:
        return f"{n} {one}"
    if 2 <= n10 <= 4 and not 12 <= n100 <= 14:
        return f"{n} {few}"
    return f"{n} {many}"


def rounds(n):
    return plural(n, "раунд", "раунда", "раундов")


def cap(s):
    return s[:1].upper() + s[1:]


def tier_numbers(set_spec, kind, tier):
    e = dict(TPL[kind][tier])
    for k, dv in set_spec.get("mod", {}).get(kind, {}).items():
        e[k] = max(1, e[k] + dv)
    return e


def targets(kind, tier, eff):
    if kind == "buff":
        rule = "allies" if tier == "all" else ("ally_strong" if eff[2]["st"] in OFFENSIVE else "ally_lowest")
    else:
        rule = TGT[kind][tier]
    return rule, None if tier == "all" else (GROUP_N[kind] if tier == "grp" else 1)


def buff_whom(eff, tier):
    strong = eff[2]["st"] in OFFENSIVE
    if tier == "grp":
        return "двум самым сильным союзникам" if strong else "двум самым раненым союзникам"
    return "самому сильному союзнику" if strong else "самому раненому союзнику"


def describe(kind, tier, e, eff):
    E = cap(eff[0]) if eff else ""
    c, left, mx = e.get("coef"), e.get("left"), e.get("max")
    if kind == "dmg":
        return {"all": f"Бьёт всех врагов — по {c} %", "grp": f"Бьёт трёх врагов — по {c} %", "one": f"Мощный удар по цели — {c} %"}[tier]
    if kind == "heal":
        return {"all": f"Лечит всех своих — по {c} %", "grp": f"Лечит троих самых раненых — по {c} %",
                "one": f"Сильно лечит самого раненого — {c} %"}[tier]
    if kind == "shield":
        return {"all": f"Щит всем своим — по {c} %", "grp": f"Щит троим самым раненым — по {c} %",
                "one": f"Крепкий щит самому раненому — {c} %"}[tier]
    if kind in ("dot", "hot"):
        who = {"dot": {"all": "на всех врагов", "grp": "на трёх врагов", "one": "на цель"},
               "hot": {"all": "на всех своих", "grp": "на троих самых раненых", "one": "на самого раненого"}}[kind][tier]
        return f"{E} {who}: {c} % за ход, {rounds(left)}" + (f", до {mx} стаков" if mx > 1 else "")
    if kind == "ctrl":
        who = {"all": "на всех врагов", "grp": "на двух самых опасных врагов", "one": "на самого опасного врага"}[tier]
        return f"{E} {who}, {rounds(left)}"
    if kind == "debuff":
        who = {"all": "на всех врагов", "grp": "на двух врагов", "one": "на цель"}[tier]
        return f"{E} {who}, {rounds(left)}"
    who = "всему отряду" if tier == "all" else buff_whom(eff, tier)
    return f"{E} {who}, {rounds(left)}"


def describe_ult(kind, tier, e, eff, pow_txt):
    E = cap(eff[0]) if eff else ""
    c, left = e.get("coef"), e.get("left")
    if kind == "dmg":
        return {"all": f"Крупный урон по всем врагам — по {c} %", "grp": f"Крупный урон по трём врагам — по {c} %",
                "one": f"Крупный урон по цели — {c} %"}[tier]
    if kind == "heal":
        return {"all": f"Крупное лечение всего отряда — по {c} %", "one": f"Крупное лечение самого раненого — {c} %"}[tier]
    if kind == "shield":
        return f"Крепкий щит всему отряду — по {c} %"
    if kind == "dot":
        return f"{E} на всех врагов: сразу {ULT_STACKS} стака по {c} %, {rounds(left)}"
    if kind == "hot":
        return f"{E} на весь отряд: сразу {ULT_STACKS} стака по {c} %, {rounds(left)}"
    if kind == "ctrl":
        return f"{E} на всех врагов, {rounds(left)}"
    if kind == "debuff":
        return f"{E} на всех врагов: {pow_txt}, {rounds(left)}"
    return f"{E} всему отряду: {pow_txt}, {rounds(left)}"


def sentence(base, twist):
    return base + (f"; {twist}" if twist else "") + "."


def src_of(no):
    if no is None:
        return None
    a = TABLE[no]
    return {"no": no, "name": a["Название"], "school": a["Элемент"], "type": a["Тип"], "text": a["Эффект"].strip()}


def build_set(sname, S):
    out = {"eff": {k: {"n": v[0], "d": v[1], **v[2]} for k, v in S["eff"].items()}, "active": [], "ult": [], "passive": [], "reaction": []}
    for kind in KINDS:
        specs = S["act"][kind]
        assert len(specs) == 3, (sname, kind)
        eff = S["eff"].get(kind)
        for tier, (name, twist, fields, no) in zip(TIERS, specs):
            e = tier_numbers(S, kind, tier)
            rule, n = targets(kind, tier, eff)
            a = {"id": f"{sname}.{kind}.{tier}", "n": name, "set": sname, "kind": kind, "tier": tier, "tgt": rule, "targets": n,
                 "ch": CTRL_CH if kind == "ctrl" else CH, **e, **(eff[2] if eff else {}), **fields,
                 "twist": twist, "d": sentence(describe(kind, tier, e, eff), twist)}
            if kind in ("dmg", "heal", "shield", "dot", "hot"):
                a["stat"] = "main"
            if no:
                a["src"] = src_of(no)
            out["active"].append(a)
    assert set(KINDS) <= {u[0] for u in S["ult"]}, sname   # у каждого вида — своя ульта; бывают и лишние, как «Тысяча птиц»
    for kind, tier, name, twist, fields, no in S["ult"]:
        eff = S["eff"].get(kind)
        e = tier_numbers(S, kind, tier)
        if "coef" in e:
            e["coef"] *= ULT_POW
        if kind in ULT_LONGER:
            e["left"] += ULT_LONGER[kind]
        if kind in ("dot", "hot"):
            e["max"] = max(e["max"], ULT_STACKS)
            e["stacks"] = ULT_STACKS
        fields = dict(fields)
        key = fields.pop("key", kind)
        pow_txt = fields.pop("powTxt", "")
        d = fields.pop("d", None) or sentence(describe_ult(kind, tier, e, eff, pow_txt), twist)
        rule, n = targets(kind, tier, eff)
        u = {"id": f"{sname}.ult.{key}", "n": name, "set": sname, "kind": kind, "tier": tier, "tgt": rule, "targets": n,
             "ch": ULT_CH, "ult": True, **e, **(eff[2] if eff else {}), **fields, "twist": twist, "d": d}
        if kind in ("dmg", "heal", "shield", "dot", "hot"):
            u["stat"] = "main"
        if no:
            u["src"] = src_of(no)
        out["ult"].append(u)
    for name, d, fields, no in S["pas"]:
        p = {"id": f"{sname}.pas.{len(out['passive']) + 1}", "n": name, "set": sname, "kind": "passive", "d": d, **fields}
        if no:
            p["src"] = src_of(no)
        out["passive"].append(p)
    for trig, name, d, fields in S["react"]:
        assert trig in TRIG, trig
        out["reaction"].append({"id": f"{sname}.react.{len(out['reaction']) + 1}", "n": name, "set": sname, "kind": "reaction",
                                "trig": trig, "d": d, **fields})
    assert len(out["passive"]) >= BASE_PAS and len(out["reaction"]) == 4, sname   # первые четыре пассивки — прежние, дальше — черты ADR-0050
    return out


