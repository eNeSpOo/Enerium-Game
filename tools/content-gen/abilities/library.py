UI_SKIP = {"id", "n", "set", "kind", "tier", "twist", "d", "src", "trig", "two"}


def ui_num(x):
    """Главные числа способности одной строкой — подпись плитки в UI-ките."""
    k, t = x["kind"], x.get("tier")
    c, left, mx, n = x.get("coef"), x.get("left"), x.get("max"), x.get("targets")
    grp = f" · {n} цели" if t == "grp" and n else ""
    if x.get("also"):   # сочетание: числа обеих частей
        first = ui_num({k_: v for k_, v in x.items() if k_ != "also"})
        return f"{first} + {ui_num({**x['also'], 'targets': x['also'].get('targets') or x.get('targets')})}"
    if x.get("shieldPct"):
        return f"{x['shieldPct']} % здоровья"
    if x.get("rewind"):
        return f"возврат за {rounds(x['rewind'])}"
    if k in ("dmg", "heal", "shield"):
        return f"{'по ' if t != 'one' else ''}{c} %{grp}"
    if k in ("dot", "hot"):
        more = f" · сразу {x['stacks']}" if x.get("stacks") else (f" · до {mx}" if mx and mx > 1 else "")
        return f"{c} % · {rounds(left)}{more}{grp}"
    if k in ("ctrl", "debuff", "buff"):
        return f"{rounds(left)}{grp}"
    if k == "reaction":
        return "когда " + TRIG[x["trig"]]
    if k == "farm":
        return "ульта" if x.get("ult") else "активка"
    return "пассивка"


def ui_item(x, typ):
    s = x.get("src")
    return {"id": x["id"], "n": x["n"], "set": x["set"], "t": typ, "k": "farm" if x["kind"] in ("farm", "farmPassive") else x["kind"],
            "tier": x.get("tier"), "trig": x.get("trig"), "d": x["d"], "tw": x.get("twist") or "", "num": ui_num(x), "ch": x.get("ch"),
            "src": [s["no"], s["name"], s["text"], s["school"], s["type"]] if s else None,
            "data": {k: v for k, v in x.items() if k not in UI_SKIP}}


def write_ui(lib, every):
    sets = []
    for sname, s in lib["sets"].items():
        items = [ui_item(x, typ) for part, typ in (("active", "act"), ("ult", "ult"), ("passive", "pas"), ("reaction", "react")) for x in s[part]]
        sets.append({"n": sname, "eff": {k: [v["n"], v["d"]] for k, v in s["eff"].items()}, "items": items})
    farm = lib["farm"]
    sets.append({"n": "Фарм", "eff": None,
                 "items": [ui_item(x, typ) for part, typ in (("passive", "pas"), ("active", "act"), ("ult", "ult")) for x in farm[part]]})
    # девятый набор UI-кита — сочетания (ADR-0050): set записи — школа первой части (по ней ядро ищет связки школы), parts — из чего она
    sets.append({"n": COMBO_SET, "eff": None, "combo": True,
                 "items": [ui_item(x, typ) for part, typ in (("active", "act"), ("ult", "ult")) for x in lib["combos"][part]]})
    # словарь эффектов для экранов (ADR-0052): имя, что это коротко, определение с числами набора и шаблон объяснения с числами ядра
    fx = {k: {f: v[f] for f in ("n", "school", "kind", "gloss", "t", "base", "def") if f in v} for k, v in lib["fx"].items()}
    data = {"total": len(every), "sets": sets,
            "kinds": {**KIND_NAME, "passive": "Пассивка", "reaction": "Реакция", "farm": "Фарм"},
            "tiers": {**TIER_NAME, "self": "На этаж"}, "triggers": TRIG, "fx": fx,
            "rules": {"ch": CH, "ctrlCh": CTRL_CH, "ultCh": ULT_CH, "ultPow": ULT_POW, "capBp": 6000, "farmStacks": True, "trigPct": TRIG_PCT,
                      "basePas": BASE_PAS, "comboPct": COMBO_PCT, "comboSet": COMBO_SET, "descMax": DESC_MAX}}
    emit(OUT_UI, "/* Собрано tools/content-gen/abilities/library.py — библиотека способностей по ADR-0015, ADR-0050 и ADR-0052. Руками не править.\n"
                      "   Черновик: номер — строка таблицы автора (имя могло смениться по лору 01.10.2026), остальные названия автор принял как рабочие; числа — демонстрация.\n"
                      "   Набор «Сочетания» (ADR-0050): запись — способность из двух, data.parts — id частей, data.also — вторая часть, set — школа первой части.\n"
                      "   Описания d (ADR-0052) объясняют эффекты; fx — словарь эффектов по ключу ядра: n — название, gloss — что это коротко, def — определение,\n"
                      "   t — шаблон объяснения контроля, дебаффа и баффа: {p} — сила в процентах, {b} — порог удара, {e} — уклонение в процентах;\n"
                      "   часть шаблона в квадратных скобках — только если у эффекта есть её число; base — числа эффекта набора. */\n"
                      "window.EN_ABILITIES = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")


# ---------------- проверка мутацией законов описаний (ADR-0052) ----------------
def mutate():
    """Каждая поломка описаний — и свой закон должен её поймать; затем правки баланса — и описание должно смениться само.
    Данные сборщика возвращаются на место после каждой поломки. Возвращает (строки отчёта, сколько не поймано)."""
    import copy
    G = globals()
    keep = {k: copy.deepcopy(G[k]) for k in ("SETS", "FARM", "TPL", "TRIG_PCT", "TRIG_TPL", "FXW")}
    fns = {k: G[k] for k in ("describe", "combo_text", "settle")}

    def restore():
        for k, v in keep.items():
            G[k].clear()
            G[k].update(copy.deepcopy(v))
        G.update(fns)

    def pas(school, i, text=None, **data):
        name, old, f, no = SETS[school]["pas"][i]
        SETS[school]["pas"][i] = (name, old if text is None else text, {**f, **data}, no)

    def react(school, i, text):
        trig, name, _, f = SETS[school]["react"][i]
        SETS[school]["react"][i] = (trig, name, text, f)

    def eff(school, kind, text=None, **data):
        name, old, d = SETS[school]["eff"][kind]
        SETS[school]["eff"][kind] = (name, old if text is None else text, {**d, **data})

    def twist(school, kind, i, text):
        name, _, f, no = SETS[school]["act"][kind][i]
        SETS[school]["act"][kind][i] = (name, text, f, no)

    def bare_active():
        G["describe"] = lambda s, a, f=fns["describe"]: f(s, a).split(":")[0] if a["kind"] == "debuff" else f(s, a)

    def bare_combo():   # вторая часть — контроль, дебафф или бафф: раунды остаются (закон Б2 доволен), объяснение выпало
        G["combo_text"] = lambda *a, f=fns["combo_text"]: f(*a).rsplit(":", 1)[0] if a[1]["kind"] in SHORTER else f(*a)

    def no_gloss():
        G["settle"] = lambda text: TOLD_RX.sub("", REF_RX.sub("", text))

    def long_text():
        pas("Огонь", 1, SETS["Огонь"]["pas"][1][1].rstrip(".") + " — и так далее" * 20 + ".")

    breaks = [   # (что сломано, закон, поломка)
        ("активная называет эффект без объяснения — «Осыпание на цель, 4 раунда.»", "О1", bare_active),
        ("пассивка называет эффект без объяснения — «по целям с осыпанием»", "О1", lambda: pas("Земля", 2, "+{pct} % урона по целям с осыпанием.")),
        ("реакция называет эффект без объяснения — «каменная кожа на 2 раунда»", "О1", lambda: react("Земля", 2, "Когда {when}, каменная кожа на {left:r}.")),
        ("связка называет эффект без объяснения — «по целям под горением»", "О1", lambda: twist("Огонь", "dmg", 1, "+{vsDot} % по целям под горением")),
        ("сочетание называет эффект второй части без объяснения", "О1", bare_combo),
        ("скобки с объяснением выпали из всех описаний", "О1", no_gloss),
        ("у эффекта пропало короткое объяснение", "О1", lambda: FXW["стужа"].update(gloss="")),
        ("короткое объяснение ничего не объясняет — «особый эффект»", "О1", lambda: FXW["стужа"].update(gloss="особый эффект")),
        ("объяснение эффекта набора ничего не объясняет — «так задумано»", "О1", lambda: eff("Земля", "debuff", "так задумано")),
        ("название эффекта не видно закону: основы слов не его", "О1", lambda: FXW["осыпание"].update(stems="обвал~")),
        ("объяснение своими словами — не об этом эффекте", "О1",
         lambda: react("Свет", 3, "Когда {when}, есть шанс наложить на него {ctrl.acc}{ctrl.said} на {then[left]:r}: так ему и надо.")),
        ("число вписано в текст пассивки руками", "О2", lambda: pas("Тьма", 0, "Герой лечится на 5 % любого нанесённого урона.")),
        ("число вписано в объяснение эффекта руками", "О2", lambda: eff("Огонь", "debuff", "+20 % получаемого урона")),
        ("число вписано в текст события руками", "О2", lambda: TRIG_TPL.update(low="здоровье героя ниже 25 %")),
        ("описание длиннее предела", "О3", long_text),
        ("в описании знак разметки", "О3", lambda: pas("Вода", 1, "+{pct} % лечения по целям <ниже> {belowPct} % здоровья.")),
        ("у реакции не сказано, когда она срабатывает", "О4", lambda: react("Вода", 2, "Следующее лечение героя на {nextHealPct} % сильнее.")),
    ]
    out, missed = [], 0
    for label, law, brk in breaks:
        brk()
        try:
            build()
            got = ""
        except LawError as e:
            got = str(e)
        except AssertionError as e:
            got = f"другой закон: {e}"
        finally:
            restore()
        hit = [line for line in got.split("\n") if line.startswith(law + ":")]
        missed += not hit
        out.append(f"{'пойман' if hit else 'НЕ ПОЙМАН'} · {law} · {label} → {(hit[0] if hit else got or 'сборка прошла')[:150]}")

    # правка баланса меняет описание сама: число в данных — и в тексте новое число, прежнего нет
    base = {x["id"]: x["d"].replace(NB, " ") for x in build()[1]}
    moves = [   # (что правим, правка, записи, было в тексте, стало в тексте)
        ("сила осыпания 30 → 40 %", lambda: eff("Земля", "debuff", pow=4000),
         ["Земля.debuff.one", "Земля.debuff.grp", "Земля.debuff.all", "Земля.pas.5", "Сочетания.act.7"], "−30 % физической защиты", "−40 % физической защиты"),
        ("коэффициент удара «на одного» 300 → 310 %", lambda: TPL["dmg"]["one"].update(coef=310),
         ["Огонь.dmg.one", "Вода.dmg.one", "Без школы.dmg.one"], "300 % атаки", "310 % атаки"),
        ("ульта от него же: 600 → 620 %", lambda: TPL["dmg"]["one"].update(coef=310), ["Огонь.ult.dmg", "Без школы.ult.dmg"], "600 % атаки", "620 % атаки"),
        ("дебафф «на одного» 4 → 5 раундов", lambda: TPL["debuff"]["one"].update(left=5), ["Земля.debuff.one", "Огонь.debuff.one"], "4 раунда", "5 раундов"),
        ("порог «Упорства» 50 → 40 % здоровья", lambda: TRIG_PCT.update(half=40), ["Земля.react.3"], "ниже 50 %", "ниже 40 %"),
        ("пассивка «Тяжёлая поступь» 10 → 12 %", lambda: pas("Земля", 2, pct=12), ["Земля.pas.3"], "+10 % урона", "+12 % урона"),
        ("порог льда «Крепкого льда» 25 → 35 %", lambda: pas("Вода", 4, breakPct=35), ["Вода.pas.5"], "больше 25 %", "больше 35 %"),
        ("горение «на одного» 40 → 45 % — у активной, «Тлеющего следа», шипов щита и реакции", lambda: TPL["dot"]["one"].update(coef=45),
         ["Огонь.dot.one", "Огонь.pas.1", "Огонь.shield.one", "Огонь.react.1"], "40 % атаки", "45 % атаки"),
    ]
    for label, move, ids, old, new in moves:
        move()
        try:
            now, err = {x["id"]: x["d"].replace(NB, " ") for x in build()[1]}, ""
        except (LawError, AssertionError) as e:
            now, err = {}, f"сборка упала: {str(e)[:120]}"
        finally:
            restore()
        bad = [i for i in ids if not (old in base[i] and new in now.get(i, "") and old not in now.get(i, ""))]
        missed += bool(err or bad)
        out.append(f"{'НЕ СЛЕДУЕТ' if err or bad else 'следует'} · {label}: описаний {len(ids)}" + (f" → {err or bad}" if err or bad else ""))
    build()   # данные на месте: сборка снова чистая
    return out, missed


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    if "--mut" in sys.argv:
        out, missed = mutate()
        print("\n".join(out))
        print(f"Проверка мутацией описаний (ADR-0052): поломок и правок баланса {len(out)}, не поймано {missed}.")
        sys.exit(1 if missed else 0)
    try:
        lib, every = build()
    except LawError as e:
        print(f"Законы описаний О1–О4 (ADR-0052) нарушены — файлы не пишутся:\n{e}")
