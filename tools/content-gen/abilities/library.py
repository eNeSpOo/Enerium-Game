# ---------------- перевод на 10 раундов (ADR-0010) ----------------
CH_BY_PRICE = {2: 3000, 3: 2500, 4: 2000, 5: 1700, 6: 1500, 8: 1200}   # цена в атаках → шанс за ход
TIER_CH = {1: 3000, 2: 2000, 3: 1500}                                  # новые удары и лечения: малое, среднее, большое
MASS_CH, GUARD_CH, ULT_CH = 1500, 2500, 1000
ATK_TO_ROUNDS = (6, 10)                                                # всё, что таблица мерит атаками, × 0,6


def rounds_of(n):
    """5 атак → 3 раунда, 4 и 3 → 2, 2 и 1 → 1, 6 → 4, 10 → 6."""
    return max(1, round(n * ATK_TO_ROUNDS[0] / ATK_TO_ROUNDS[1]))


