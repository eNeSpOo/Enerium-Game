def describe(sname, a):
    """Что делает активная способность или ульта — из её данных: вид, цели, числа; у эффекта — название и что он делает (ADR-0052).
    a — запись или часть сочетания: вид, ступень, правило цели и числа; sname — её школа."""
    kind, tier, ult = a["kind"], a["tier"], a.get("ult")
    c, left, who = a.get("coef"), a.get("left"), (a["tgt"], a.get("targets"))
    if kind == "dmg":
        if ult:
            return {"all": f"Крупный урон по всем врагам — по {c} % атаки", "grp": f"Крупный урон по трём врагам — по {c} % атаки",
                    "one": f"Крупный урон по цели — {c} % атаки"}[tier]
        return {"all": f"Бьёт всех врагов — по {c} % атаки", "grp": f"Бьёт трёх врагов — по {c} % атаки",
                "one": f"Мощный удар по цели — {c} % атаки"}[tier]
    if kind == "heal":
        if ult:
            return {"all": f"Крупное лечение всего отряда — по {c} % атаки", "one": f"Крупное лечение самого раненого — {c} % атаки"}[tier]
        return {"all": f"Лечит всех своих — по {c} % атаки", "grp": f"Лечит троих самых раненых — по {c} % атаки",
                "one": f"Сильно лечит самого раненого — {c} % атаки"}[tier]
    if kind == "shield":
        if ult:
            return f"Крепкий щит всему отряду — по {c} % атаки"
        return {"all": f"Щит всем своим — по {c} % атаки", "grp": f"Щит троим самым раненым — по {c} % атаки",
                "one": f"Крепкий щит самому раненому — {c} % атаки"}[tier]
    fx = FXS[sname][kind]
    if kind in ("dot", "hot"):
        on = "на весь отряд" if ult and kind == "hot" else WHO[who]
        return f"{fx.N} {on}, {rounds(left)}: {fx.per_text(a, a.get('stacks'))}"
    if kind in ("ctrl", "debuff"):
        return f"{fx.N} {WHO[who]}, {rounds(left)}: {fx.tell(a)}"
    return f"{fx.N} {WHOM[who]}, {rounds(left)}: {fx.tell(a)}"


def sentence(base, twist):
    return base + (f"; {twist}" if twist else "") + "."


def entry_text(sname, a, twist="", custom=None):
    """Описание записи: своё (custom) или собранное describe, со связкой twist; шаблоны берут числа записи. Без точки, со служебными знаками."""
    if custom:
        return fmt(custom, sname, a).rstrip(".")
    return sentence(describe(sname, a), fmt(twist, sname, a)).rstrip(".")


