class Fmt(string.Formatter):
    """Шаблон описания: {поле} — число из данных записи; после двоеточия — как его написать."""
    def format_field(self, v, spec):
        if spec == "r":
            return rounds(v)
        if spec == "rabs":
            return rounds(abs(v))
        if spec == "bp":
            return pct_bp(v)
        if spec == "mul":
            return mul_bp(v)
        if spec == "x":
            return TIMES[v]
        if spec == "of":
            return ORD_F[v]
        if spec == "om":
            return ORD_M[v]
        if spec == "st":
            return plural(v, "стак", "стака", "стаков")
        if spec == "sti":
            return plural(v, "стаком", "стаками", "стаками")
        if spec == "hits":
            return cap(NUM_W[v]) + plural(v, "удар", "удара", "ударов")[len(str(v)):]
        if spec == "harm":
            return plural(v, "вредный эффект", "вредных эффекта", "вредных эффектов")
        if spec == "soul":
            return plural(v, "душа", "души", "душ")
        if spec == "turn":
            return plural(v, "ход", "хода", "ходов")
        if spec == "foes":
            return FOES_ACC[v]
        return super().format_field(v, spec)


