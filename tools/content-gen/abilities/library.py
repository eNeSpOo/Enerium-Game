# ---------------- сборка ----------------
def plural(n, one, few, many):
    n10, n100 = abs(n) % 10, abs(n) % 100
    if n10 == 1 and n100 != 11:
        return f"{n} {one}"
    if 2 <= n10 <= 4 and not 12 <= n100 <= 14:
        return f"{n} {few}"
    return f"{n} {many}"


def rounds(n):
    return plural(n, "раунд", "раунда", "раундов")


def cap(s):
    return s[:1].upper() + s[1:]


def tier_numbers(set_spec, kind, tier):
    e = dict(TPL[kind][tier])
    for k, dv in set_spec.get("mod", {}).get(kind, {}).items():
        e[k] = max(1, e[k] + dv)
    return e


def targets(kind, tier, eff):
    if kind == "buff":
        rule = "allies" if tier == "all" else ("ally_strong" if eff[2]["st"] in OFFENSIVE else "ally_lowest")
    else:
        rule = TGT[kind][tier]
    return rule, None if tier == "all" else (GROUP_N[kind] if tier == "grp" else 1)


