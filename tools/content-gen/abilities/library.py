RU = "[а-яё]"
REF_A, REF_B, TOLD_A, TOLD_B = "\ue000", "\ue001", "\ue002", "\ue003"   # служебные знаки шаблона: «объясни в скобках» и «объяснено здесь»
REF_RX, TOLD_RX = re.compile(f"{REF_A}([^{REF_B}]+){REF_B}"), re.compile(f"{TOLD_A}([^{TOLD_B}]+){TOLD_B}")


def rx_src(pattern):
    """Образец словаря → регулярное выражение, одно для Python и JS: текст сверяется в нижнем регистре."""
    return f"(?<!{RU})(?:" + pattern.replace("~", f"{RU}*").replace("!", f"(?!{RU})") + ")"


def pct_bp(bp):
    """Базисные пункты → проценты целым числом: 2500 → «25», 3333 → «33»."""
    return str((bp + 50) // 100)


def mul_bp(bp):
    """Множитель в б. п. → число: 15000 → «1,5», 20000 → «2»."""
    whole, frac = divmod(bp, 10000)
    return (f"{whole},{frac:04d}".rstrip("0")).rstrip(",")


