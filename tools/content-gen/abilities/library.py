#          фарм-пассивка, бойцу урона — прибавки к удару. Герою другой роли такая черта не даётся; своей роли — связана «по роли»,
#          даже если остальные условия пусты;
#   crit — условие «герой нанёс крит»: физический боец (ловкость — вторая или первая степень роста), сильнее — с активкой-ударом;
#   kill — условие «герой добил врага»: своя активка-удар или боец урона.
# Пассивка без связки чертой не становится: она ждёт ульты, гибели союзника или не связана ни с чем.
