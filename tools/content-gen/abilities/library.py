# ---------------- сочетания (ADR-0050) ----------------
PART_SKIP = {"id", "n", "set", "tier", "twist", "d", "src", "ch", "ult"}   # что часть не несёт: свои у сочетания
SCALED = ("dmg", "heal", "shield", "dot", "hot")                           # виды с коэффициентом: 60 % своих
SHORTER = ("ctrl", "debuff", "buff")                                       # виды с длительностью эффекта: на раунд короче


def combo_part(a):
    """Часть сочетания по правилу силы Б2: коэффициент — COMBO_PCT % своего, контроль, дебафф и бафф — на раунд короче."""
    part = {k: v for k, v in a.items() if k not in PART_SKIP}
    if a["kind"] in SCALED and "coef" in part:
        assert part["coef"] * COMBO_PCT % 100 == 0, (a["id"], "коэффициент части — не целый")
        part["coef"] = part["coef"] * COMBO_PCT // 100
    if a["kind"] in SHORTER:
        part["left"] = max(1, part["left"] - COMBO_SHORTER)
    return part


def combo_text_ok(part, text):
    """Числа части стоят в тексте сочетания: коэффициент и длительность."""
    need = []
    if part["kind"] in SCALED and "coef" in part:
        need.append(f"{part['coef']} %")
    if "left" in part and part["kind"] != "shield":
        need.append("1 раунд" if part["left"] == 1 else f"{part['left']} раунда")
    return [x for x in need if x not in text.replace(NB, " ")]


NUM_DAT = {2: "двум", 3: "трём"}


def combo_text(A, B, first, second, rule):
    """Что делает сочетание — из его частей (ADR-0052): первая часть — шаблонами своей записи с числами части; вторая — так же,
    если цели у неё свои, иначе — «кому» (тем же целям или себе), название эффекта и что он делает. Со служебными знаками, без точки."""
    lvl = {"ult": True} if A.get("ult") else {}
    tw1, over = TW[A["id"]], (A.get("atStacks") or {})
    if rule == "same" and over.get("st") and over["st"] == B.get("st") and second["left"] >= over["left"]:
        tw1 = ""   # связку первой части перекрывает вторая: тот же эффект на ту же цель и не короче — в тексте он назван один раз
    t1 = entry_text(A["set"], {**first, "tier": A["tier"], **lvl}, tw1, CUSTOM.get(A["id"]))
    if rule == "own":
        t2 = entry_text(B["set"], {**second, **lvl}, TW[B["id"]], CUSTOM.get(B["id"]))
        return f"{t1}; {t2[:1].lower() + t2[1:]}"
    assert B["kind"] in ("dot", "hot", "ctrl", "debuff", "buff") and not TW[B["id"]], (B["id"], "вторая часть по целям первой — эффект без связки")
    fx = FXS[B["set"]][B["kind"]]
    n1, n2 = first.get("targets"), second.get("targets")
    if rule == "self":
        whom = "себе"
    elif A["tier"] == "one":
        whom = "ей же" if first["tgt"] == "threat" else "ему же"   # «цель» — она, «враг» и «союзник» — он
    elif n2 is None:
        whom = "каждому"
    else:
        whom = "им же" if n2 >= n1 else f"{NUM_DAT[n2]} первым"
    return f"{t1}; {whom} — {fx.n}, {rounds(second['left'])}: {fx.per_text(second) if fx.per else fx.tell(second)}"


def build_combos(lib):
    """Сочетания — законы Б1–Б5: любая ошибка — сборка падает."""
    by = {x["id"]: x for s_ in lib["sets"].values() for part in ("active", "ult") for x in s_[part]}
    out = {"active": [], "ult": []}
    for name, ida, idb, rule, opt in COMBOS:
        assert ida in by and idb in by, (name, "Б1: части — записи библиотеки")
        A, B = by[ida], by[idb]
        ult = bool(A.get("ult"))
        assert ult == bool(B.get("ult")), (name, "Б1: части одного уровня — две активки или две ульты")
        assert A["set"] != "Без школы" or B["set"] == "Без школы", (name, "Б4: школа — школа первой части")
        two = B["set"] not in (A["set"], "Без школы")
        assert rule in ("own", "same", "self"), (name, "Б3: цели второй части")
        first, second = combo_part(A), combo_part(B)
        if opt.get("tgt"):
            first["tgt"] = opt["tgt"]
        if rule == "same":
            assert not (A["tier"] == "all" or B["tier"] == "all"), (name, "Б3: цели первой — не у массовых частей")
            second["tgt"], second["targets"] = "same", (B["targets"] if B["tier"] == "grp" else None)
            assert second["targets"] is None or second["targets"] <= A["targets"], (name, "Б3: второй части целей не больше, чем у первой")
        elif rule == "self":
            second["tgt"], second["targets"] = "self", 1
        second["school"], second["tier"] = B["set"], B["tier"]
        part_key = "ult" if ult else "active"
        key = "ult" if ult else "act"
        cid = f"{COMBO_SET}.{key}.{len(out[part_key]) + 1}"
        text = done(cid, combo_text(A, B, first, second, rule))
        for part in (first, second):
            miss = combo_text_ok(part, text)
            assert not miss, (name, "Б2: в тексте нет чисел части", miss)
        c = {"id": cid, "n": name, "set": A["set"], "tier": A["tier"],
             "ch": ULT_CH if ult else CH, **({"ult": True} if ult else {}), **first, "also": second,
             "parts": [ida, idb], "combo": True, "two": two, "twist": "", "d": text}
        assert all(isinstance(v, int) for v in (c.get("coef", 0), c.get("left", 0), second.get("coef", 0), second.get("left", 0))), name
        out[part_key].append(c)
    return out


