# Пассивки: вид → (роль, связка). Связка — когда пассивка работает как черта героя с доблести 0:
#   own  — её условие кладёт или её действие несёт своя активка доблести 0 («Раздувание» и горение, «Крепкий лёд» и заморозка);
#   any  — условие кладёт своя активка или соседи по циклу («Жар в крови» и горение, «Тяжёлая поступь» и осыпание);
