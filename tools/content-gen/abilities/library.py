def ctx_of(sname, entry, **more):
    """Поля шаблона записи: её данные, эффекты её школы (dot, hot, ctrl, debuff, buff), эффект любой школы по ключу (fx), кровотечение."""
    c = dict(entry)
    c.update({kind: fx.bind(entry) for kind, fx in FXS.get(sname, {}).items()})
    c.update(fx=FX, bleed=FXS["Без школы"]["dot"], **more)
    if entry.get("hits"):
        c["each"] = entry["coef"] // entry["hits"]   # «пять ударов по 120 %» — коэффициент на все удары
    return c


def fmt(text, sname, entry, **more):
    return FMT.format(text, **ctx_of(sname, entry, **more)) if text else ""


def settle(text):
    """Служебные знаки шаблона — в текст: «объясни в скобках» встаёт у первого упоминания эффекта, и только если тот не объяснён
    с числами в том же описании."""
    told, seen = set(TOLD_RX.findall(text)), set()

    def ref(m):
        k = m.group(1)
        if k in told or k in seen:
            return ""
        seen.add(k)
        return f" ({FX[k].gloss})"
    return TOLD_RX.sub("", REF_RX.sub(ref, text))


NB = "\u00a0"


def nb(text):
    """Неразрывные пробелы готового текста: число не отрывается от «%» и своего слова («25 %», «3 раунда»), тире и знак умножения —
    от слова перед ними. Экран узкий: перенос строки не должен ставить «%» или тире в начало строки."""
    text = re.sub(r"([\d}]) (?=[%а-яёА-ЯЁ])", r"\1" + NB, text)
    return re.sub(r"(×) (?=[\d{])", r"\1" + NB, re.sub(r" (?=[—×])", NB, text))


def plain(text):
    """Текст для сверки образцами: нижний регистр, пробелы обычные."""
    return text.lower().replace(NB, " ")


def marked(text):
    """Эффекты, которые шаблон объяснил сам: в скобках или с числами."""
    return set(REF_RX.findall(text)) | set(TOLD_RX.findall(text))


def named(text):
    """Эффекты, названные в готовом тексте, — по основам слов."""
    low = plain(text)
    return {fx.key for fx in FX.values() if re.search(fx.stems, low)}


def unproved(text):
    """Закон О1 по тексту: названия эффектов, рядом с которыми нет слов объяснения. Тот же закон — у check_texts.js для врагов."""
    low = plain(text)
    return sorted(fx.n for fx in FX.values() if re.search(fx.stems, low) and not re.search(fx.proof, low))


