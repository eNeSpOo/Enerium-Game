def ch_txt(v):
    return "—" if v["kind"] == "passive" else f"{v['ch'] // 100} %"


def left_txt(v):
    n = v.get("left") or v.get("then", {}).get("left") or v.get("atStacks", {}).get("left")
    return f"{n} р." if n else "—"


def origin(v):
    if "src" in v:
        s = v["src"]
        dur = s["dur"] if s["dur"] not in ("", "—") else ""
        dur = dur + " атак" if dur.isdigit() else dur
        return f"№{s['no']}" + (f" · цена {s['price']}" if s["price"].isdigit() else "") + (f" · {dur}" if dur else "")
    return v.get("origin", "новое")


def names(xs):
    return ", ".join(x["n"] for x in xs)


