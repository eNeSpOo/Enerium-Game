GIVE_TRIG = {"allyLow", "allyCrit", "foeUlt", "hit", "crit", "kill", "dodge"}   # реакции этих событий кладут эффект в обычном бою, а не «раз за биом»


def tag_entry(a, S):
    """Метки записи: give, take, roles и — у пассивки и реакции — link."""
    sch, k = a["set"], a["kind"]
    eff = S["eff"] if S else {}
    debuff_st = eff["debuff"][2]["st"] if "debuff" in eff else None
    give, take, roles = set(), set(), set()

    def then_st(st):
        if st in BUFF_ROLE:
            give.add(f"buff:{st}")
        else:
            give.add(f"st:{st}")
            if st in CTRL_ST:
                give.add("ctrl")

    if k in KIND_ROLE:
        roles.add(KIND_ROLE[k])
    if k == "dmg":
        give.add("hit")
    if k == "dot":
        give.add(f"dot:{sch}")
    if k == "hot":
        give.update({f"hot:{sch}", "heal", "support"})
    if k == "heal":
        give.update({"heal", "support"})
    if k == "shield":
        give.update({"shield", "support"})
        if a.get("thorns") == "dot":
            give.add(f"dot:{sch}")
        elif a.get("thorns") == "debuff":
            give.add(f"st:{debuff_st}")
    if k in ("ctrl", "debuff"):
        then_st(a["st"])
    if k == "debuff":
        give.add("debuff")
    if k == "buff":
        give.add(f"buff:{a['st']}")
        roles.add(BUFF_ROLE[a["st"]])
    if k in ("farm", "farmPassive"):
        roles.add("фарм")
        give.add("farm")
    if a.get("thenDot") or a.get("sigIfSig"):
        give.add(f"dot:{sch}")
    if a.get("atMax"):
        give.add(f"st:{a['atMax']}")
    if isinstance(a.get("then"), dict) and a["then"].get("st"):
        then_st(a["then"]["st"])
    if any(a.get(f) for f in ("vsDot", "perStack", "consume", "reignite", "whileSig")) or (a.get("atStacks") or {}).get("st"):
        take.add(f"dot:{sch}")
    if a.get("vsDebuff"):
        take.add(f"st:{debuff_st}")
    if a.get("vsHot") or (a.get("atStacks") or {}).get("shieldPct"):
        take.add(f"hot:{sch}")
    link = None
    if k in ("passive", "reaction"):
        role, spec = (PAS_LINK[a["pas"]] if k == "passive" else TRIG_LINK[a["trig"]])
        roles.add(role)
        if k == "reaction":   # что реакция кладёт — из её данных; лечение и щит себе — не «кладёт отряду»
            th, trig = a.get("then"), a["trig"]
            if th in ("dot", "dotAll") or a.get("thenDot"):
                give.add(f"dot:{sch}")
            if th == "hot":
                give.update({f"hot:{sch}", "heal"})
            if trig == "allyCrit" and a.get("shieldPct"):
                give.add("shield")
            if a.get("healPctAll"):
                give.add("heal")
            if trig == "foeUlt" and a.get("dodge"):
                spec = {"gate": ["tank"]}          # «Уклон от бури» — стойкость, а не контроль
                roles.discard(role)
                roles.add("защита")
            if a.get("nextHealPct"):
                spec = {"own": ["heal"]}           # «Прилив сил» — своё лечение сильнее
            if th == "spreadDot":
                spec = dict(spec, any=["dot:@"])   # «Перекинувшийся огонь» — добитый враг должен гореть
            if trig not in GIVE_TRIG:
                give.clear()                       # «раз за биом» и «когда пал союзник» — не то, на что рассчитывают соседи
        if spec is not None:
            def sub(t):
                return t.replace("@debuff", debuff_st or "").replace("@st", "ctrl" if a.get("ctrl") else str(a.get("st") or debuff_st)).replace("@", sch)
            link = {key: ([sub(t) for t in v] if isinstance(v, list) else v) for key, v in spec.items()}
            link = {key: [("ctrl" if t == "st:ctrl" else t) for t in v] if isinstance(v, list) else v for key, v in link.items()}
            for t in link.get("give", []):
                give.add(t)
            for t in link.get("any", []) + [t for t in link.get("own", []) if ":" in t]:
                take.add(t)
            if k == "reaction" and give and "give" not in link and a["trig"] in GIVE_TRIG:
                link["give"] = sorted(give)
            if not link:
                link = None
    return {"give": sorted(give), "take": sorted(take), "roles": sorted(roles), **({"link": link} if link else {})}


def tag_all(lib):
    """Метки связок — каждой записи библиотеки; у сочетания — обеих частей вместе."""
    tags = {}
    for sname, S in SETS.items():
        for part in ("active", "ult", "passive", "reaction"):
            for a in lib["sets"][sname][part]:
                tags[a["id"]] = tag_entry(a, S)
    for part in ("passive", "active", "ult"):
        for a in lib["farm"][part]:
            t = tag_entry(a, None)
            if part == "passive":
                t["link"] = {"gate": ["farm"]}
            tags[a["id"]] = t
    for part in ("active", "ult"):
        for c in lib["combos"][part]:
            ta, tb = tags[c["parts"][0]], tags[c["parts"][1]]
            tags[c["id"]] = {k: sorted(set(ta[k]) | set(tb[k])) for k in ("give", "take", "roles")}
    return tags


# ---------------- законы описаний О1–О4 (ADR-0052) ----------------
BAD_CHARS = re.compile("[\ue000-\ue003{}<>&\"]|  ")   # служебные знаки шаблона и знаки, которые экран вставляет в разметку как есть


def laws(every):
    """Законы описаний: О1 — в описании нет названия эффекта без объяснения; О2 — в шаблонах нет цифр: числа только из данных;
    О3 — описание не длиннее DESC_MAX знаков и без служебных знаков. Возвращает нарушения. О4 — у реакции сказано, когда она
    срабатывает — сверяет build_set, пока собирает запись."""
    bad = []
    for where, text in TEMPLATES + [(f"событие «{k}»", v) for k, v in TRIG_TPL.items()]:
        if re.search(r"\d", re.sub(r"\{[^{}]*\}", "", text)):
            bad.append(f"О2: цифра в шаблоне — числа описания только из данных: {where}: «{text}»")
    for fx in FX.values():   # словарь сходится сам с собой: название эффекта видно по его основам, его объяснения проходят свой образец
        if not re.search(fx.stems, fx.n):
            bad.append(f"О1: название эффекта «{fx.n}» не видно по его основам слов")
        for label, s in (("коротко", fx.gloss), ("определение", eff_def(fx))):
            if not s or not re.search(fx.proof, plain(s)):
                bad.append(f"О1: слова эффекта «{fx.n}» ({label}) не проходят образец его объяснения: «{s}»")
    for x in every:
        d, raw = x["d"], RAW.get(x["id"], "")
        lost = sorted(FX[k].n for k in named(d) - marked(raw))   # назван, а шаблон его не объяснил: ни в скобках, ни с числами
        if lost:
            bad.append(f"О1: «{x['n']}» — название эффекта без объяснения ({', '.join(lost)}): «{d}»")
        elif unproved(d):
            bad.append(f"О1: «{x['n']}» — у названия нет слов объяснения ({', '.join(unproved(d))}): «{d}»")
        if len(d) > DESC_MAX:
            bad.append(f"О3: «{x['n']}» — описание длиннее {DESC_MAX} знаков ({len(d)}): «{d}»")
        if BAD_CHARS.search(d) or not d.endswith(".") or d.endswith("..") or re.search(r"\d [%а-яё]| [—×]", d):
            bad.append(f"О3: «{x['n']}» — в описании служебный знак, двойной пробел, нет точки или число оторвано от «%»: «{d}»")
    return bad


def fx_export():
    """Словарь эффектов — экранам и проверкам (ADR-0052): название, школа, вид, что это коротко (gloss), определение с числами набора
    (def), шаблон объяснения контроля, дебаффа и баффа (t: {p} — сила в процентах, {b} — порог удара, {e} — уклонение; часть
    в квадратных скобках — только если у эффекта есть её число) и числа набора (base), основы слов (stems) и образец объяснения
    (proof) закона О1 — регулярные выражения для текста в нижнем регистре."""
    nums = ("pow", "breakPct", "evadeDown")
    return {fx.key: {"n": fx.n, "school": fx.school, "kind": fx.kind, "gloss": fx.gloss,
                     **({} if fx.per else {"t": nb(fx.tpl), "base": {k: fx.data[k] for k in nums if k in fx.data}}),
                     "def": eff_def(fx), "stems": fx.stems, "proof": fx.proof} for fx in FX.values()}


def build():
    init_trig()
    init_fx()
    for box in (TW, CUSTOM, RAW):
        box.clear()
    lib = {"source": SRC["source"],
           "rules": {"kinds": KINDS, "tiers": TIERS, "groupTargets": GROUP_N, "tiersTpl": TPL, "ch": CH, "ctrlCh": CTRL_CH, "ultCh": ULT_CH,
                     "ultPow": ULT_POW, "ultLonger": ULT_LONGER, "ultStacks": ULT_STACKS, "capBp": 6000, "triggers": TRIG, "trigPct": TRIG_PCT,
                     "farmStacks": True, "noSchool": "приёмы «Без школы» — любому герою (ADR-0050); герою без стихии и фарм-герою — как своя школа",
                     "basePas": BASE_PAS, "comboPct": COMBO_PCT, "comboShorter": COMBO_SHORTER, "comboSet": COMBO_SET, "comboTwoSrc": COMBO_TWO_SRC,
                     "descMax": DESC_MAX},
           "fx": fx_export(),
           "sets": {name: build_set(name, S) for name, S in SETS.items()}, "farm": build_farm()}
    lib["combos"] = build_combos(lib)
    lib["tags"] = tag_all(lib)
    every = [x for s in lib["sets"].values() for part in ("active", "ult", "passive", "reaction") for x in s[part]]
    every += [x for part in ("passive", "active", "ult") for x in lib["farm"][part]]
    every += [x for part in ("active", "ult") for x in lib["combos"][part]]
    bad = laws(every)
    if bad:
        raise LawError("\n".join(bad))
    names = [x["n"] for x in every]
    dup = sorted({n for n in names if names.count(n) > 1})
    assert not dup, dup
    nos = sorted(x["src"]["no"] for x in every if "src" in x)
    assert nos == list(range(1, 73)), nos
    for kind in ("ctrl", "debuff", "buff"):
        sts = [S["eff"][kind][2]["st"] for S in SETS.values()]
        assert len(set(sts)) == len(sts), (kind, sts)
    return lib, every


