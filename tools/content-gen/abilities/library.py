def _nb_trig(s):
    """Число события не отрывается от «%»: неразрывный пробел, как в описаниях (nb)."""
    return s.replace(" %", "\u00a0%").replace(" —", "\u00a0—")


def init_trig():
    """Тексты событий — от порогов TRIG_PCT: сборка зовёт заново, правка порога меняет текст сама."""
    TRIG_WHEN.clear()
    TRIG_WHEN.update({k: v.format(pct=TRIG_PCT.get(k)) for k, v in TRIG_TPL.items()})
    TRIG.clear()
    TRIG.update({k: _nb_trig(v + (f" — {ONCE_TXT[TRIG_ONCE[k]]}" if k in TRIG_ONCE else "")) for k, v in TRIG_WHEN.items()})


