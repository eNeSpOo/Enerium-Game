def plural(n, one, few, many):
    n10, n100 = abs(n) % 10, abs(n) % 100
    if n10 == 1 and n100 != 11:
        return f"{n} {one}"
    if 2 <= n10 <= 4 and not 12 <= n100 <= 14:
        return f"{n} {few}"
    return f"{n} {many}"


def rounds(n):
    return plural(n, "раунд", "раунда", "раундов")


def cap(s):
    return s[:1].upper() + s[1:]


def tier_numbers(set_spec, kind, tier):
    e = dict(TPL[kind][tier])
    for k, dv in set_spec.get("mod", {}).get(kind, {}).items():
        e[k] = max(1, e[k] + dv)
    return e


def targets(kind, tier, eff):
    if kind == "buff":
        rule = "allies" if tier == "all" else ("ally_strong" if eff[2]["st"] in OFFENSIVE else "ally_lowest")
    else:
        rule = TGT[kind][tier]
    return rule, None if tier == "all" else (GROUP_N[kind] if tier == "grp" else 1)


def buff_whom(eff, tier):
    strong = eff[2]["st"] in OFFENSIVE
    if tier == "grp":
        return "двум самым сильным союзникам" if strong else "двум самым раненым союзникам"
    return "самому сильному союзнику" if strong else "самому раненому союзнику"


def describe(kind, tier, e, eff):
    E = cap(eff[0]) if eff else ""
    c, left, mx = e.get("coef"), e.get("left"), e.get("max")
    if kind == "dmg":
        return {"all": f"Бьёт всех врагов — по {c} %", "grp": f"Бьёт трёх врагов — по {c} %", "one": f"Мощный удар по цели — {c} %"}[tier]
    if kind == "heal":
        return {"all": f"Лечит всех своих — по {c} %", "grp": f"Лечит троих самых раненых — по {c} %",
                "one": f"Сильно лечит самого раненого — {c} %"}[tier]
    if kind == "shield":
        return {"all": f"Щит всем своим — по {c} %", "grp": f"Щит троим самым раненым — по {c} %",
                "one": f"Крепкий щит самому раненому — {c} %"}[tier]
    if kind in ("dot", "hot"):
        who = {"dot": {"all": "на всех врагов", "grp": "на трёх врагов", "one": "на цель"},
               "hot": {"all": "на всех своих", "grp": "на троих самых раненых", "one": "на самого раненого"}}[kind][tier]
        return f"{E} {who}: {c} % за ход, {rounds(left)}" + (f", до {mx} стаков" if mx > 1 else "")
    if kind == "ctrl":
        who = {"all": "на всех врагов", "grp": "на двух самых опасных врагов", "one": "на самого опасного врага"}[tier]
        return f"{E} {who}, {rounds(left)}"
    if kind == "debuff":
        who = {"all": "на всех врагов", "grp": "на двух врагов", "one": "на цель"}[tier]
        return f"{E} {who}, {rounds(left)}"
    who = "всему отряду" if tier == "all" else buff_whom(eff, tier)
    return f"{E} {who}, {rounds(left)}"


