def entry(lib, ref):
    kind, key = ref.split(".")
    return lib["classMoves"][key] if kind == "класс" else lib["schools"][kind][key]


def frame_kit(lib, cls, school):
    """Пул способностей героя: рамка класса, наполненная школой его стихии."""
    f, kit, cm = FRAMES[cls], lib["schools"][school], lib["classMoves"]
    return {"active": [kit[c] for c in f["school"]] + [cm[k] for k in f["class"]],
            "passive": [kit[c] if c in kit else cm[c] for c in f["pas"]],
            "ult": [kit[c] if c in kit else cm[c] for c in f["ult"]]}


def build():
    lib = {"source": SRC["source"],
           "rules": {"chByPrice": CH_BY_PRICE, "tierCh": TIER_CH, "massCh": MASS_CH, "guardCh": GUARD_CH, "ultCh": ULT_CH,
                     "atkToRounds": list(ATK_TO_ROUNDS), "capBp": 6000},
           "schools": {}, "classMoves": {}, "frames": FRAMES}
    for s in SCHOOLS:
        kit = LIB[s]
        assert [c for c, _ in CELLS] == list(kit), (s, list(kit))
        lib["schools"][s] = {c: dict(kit[c], school=s, cell=c, id=f"{s}.{c}") for c, _ in CELLS}
    lib["classMoves"] = {k: dict(v, school="класс", id=f"класс.{k}") for k, v in CLASS_MOVES.items()}
    lib["foes"] = [{"foe": f, "el": el, "n": n, "ref": ref, "note": note} for f, el, n, ref, note in FOES]
    # проверки: все 72 строки таблицы учтены по разу; контроли и дебаффы школ не повторяются
    every = list(lib["classMoves"].values()) + [x for s in lib["schools"].values() for x in s.values()]
    nos = sorted(v["src"]["no"] for v in every if "src" in v)
    assert nos == list(range(1, 73)), nos
    for cell in ("ctl", "deb"):
        sts = [lib["schools"][s][cell]["st"] for s in SCHOOLS]
        assert len(set(sts)) == len(sts), (cell, sts)
    for _, _, _, ref, _ in FOES:
        entry(lib, ref)
    return lib


