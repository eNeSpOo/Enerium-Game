class Fx:
    """Эффект набора в шаблонах описаний: формы названия, объяснение с числами (t) и пометка «объясни в скобках» (g)."""
    def __init__(self, school, kind, name, text, data):
        W = FXW[name]
        self.school, self.kind, self.n, self.tpl, self.data, self.own = school, kind, name, tpl(text, f"эффект «{name}»"), data, None
        self.per = kind in PER
        self.key = f"{kind}-{school}" if self.per else data["st"]
        self.N, self.ins, self.und, self.gen, self.acc = cap(name), W["ins"], W.get("und", W["ins"]), W["gen"], W["acc"]
        self.gloss = tpl(PER[kind]["gloss"] if self.per else W["gloss"], f"эффект «{name}», коротко")
        self.stems, self.proof = rx_src(W["stems"]), rx_src(PER[kind]["proof"] if self.per else W["proof"])

    def bind(self, entry):
        """Эффект при записи: если запись сама несёт этот эффект, объяснение берёт её числа — силу, порог удара, уклонение."""
        if self.per or entry.get("st") != self.data["st"]:
            return self
        b = Fx.__new__(Fx)
        b.__dict__.update(self.__dict__)
        b.own = {k: entry[k] for k in ("pow", "breakPct", "evadeDown") if k in entry}
        return b

    @property
    def g(self):
        return REF_A + self.key + REF_B

    def told(self):
        return TOLD_A + self.key + TOLD_B

    @property
    def said(self):
        """Эффект объяснён в шаблоне своими словами: пометка «объяснено здесь» без текста — слова сверит образец объяснения (О1)."""
        return self.told()

    def tell(self, entry=None):
        """Что делает контроль, дебафф или бафф — с числами записи: {p} — сила, {b} — порог удара, {e} — уклонение."""
        assert not self.per, self.n
        d = {**self.data, **(self.own or {}), **{k: entry[k] for k in ("pow", "breakPct", "evadeDown") if entry and k in entry}}
        s = re.sub(r"\[([^\]]*)\]", lambda m: m.group(1) if d.get("evadeDown") else "", self.tpl)   # часть в скобках — только с её числом
        s = s.replace("{p}", pct_bp(d.get("pow", 0))).replace("{b}", str(d.get("breakPct", ""))).replace("{e}", pct_bp(d.get("evadeDown", 0)))
        assert "{" not in s, (self.n, s)
        return self.told() + s

    @property
    def t(self):
        return self.tell()

    def rule(self, e=None, stacks=None):
        """Своё правило урона или лечения по времени школы — сверх «урон каждый ход»; e — числа ступени, без них — определение эффекта."""
        out = []
        if self.tpl:
            out.append(FMT.format(self.tpl, **ctx_of(self.school, self.data)))
        if self.data.get("atMax"):   # на пределе стаков — дебафф школы: числа — её записи «на одного», как в ядре (addPeriodicLib)
            deb = FX[self.data["atMax"]]
            left = tier_numbers(SETS[deb.school], "debuff", "one")["left"]
            say = f"{deb.n} на {rounds(left)}: {deb.t}"
            if e is None:
                out.append(f"на пределе стаков цель получает {deb.acc}{deb.g}")
            elif stacks and stacks >= e["max"]:
                out.append(f"с ними сразу {say}")
            elif e["max"] == 1:
                out.append(f"с первым же стаком — {say}")
            else:
                out.append(f"на {e['max']} стаках — {say}")
        return "; ".join(out)

    def per_text(self, e, stacks=None, with_cap=True, left=False):
        """Урон или лечение по времени с числами ступени e: сколько за ход, предел стаков и своё правило школы."""
        what, c, mx = PER[self.kind]["what"], e["coef"], e.get("max", 1)
        if stacks:
            s = f"{what} каждый ход — сразу {plural(stacks, 'стак', 'стака', 'стаков')} по {c} % атаки"
        else:
            s = f"{what} {c} % атаки каждый ход" + (f", {rounds(e['left'])}" if left else "") + (f", до {mx} стаков" if with_cap and mx > 1 else "")
        own = self.rule(e, stacks)
        return self.told() + s + (f"; {own}" if own else "")

    def stack(self, tier, with_cap=False):
        """Один стак эффекта записи школы ступени tier — так его кладут связки, шипы щита, черты и реакции."""
        return self.per_text(tier_numbers(SETS[self.school], self.kind, tier), None, with_cap, left=True)

    t1 = property(lambda self: self.stack("one"))
    t1m = property(lambda self: self.stack("one", True))
    t_all = property(lambda self: self.stack("all"))


