    ks, opts = act0_kinds(H), {}
    ent = [] if H["farm"] else class_entries(H)

    def put(aid, c):
        c += jitter(H["id"], aid)
        if aid not in opts or c < opts[aid]:
            opts[aid] = c

    def tier_pen(a):
        prefs = tiers_of(a["kind"], farm_pool(H) if H["farm"] else ent) or list(L.TIERS)
        return A0["tier"] * (prefs.index(a["tier"]) if a["tier"] in prefs else len(prefs))

    if H["farm"]:
        for a in lib["farm"]["active"]:
            put(a["id"], A0["own"])
    for sname in dict.fromkeys(([] if H["farm"] else [H["school"]]) + [NO_SCHOOL]):
        base = A0["own"] if sname == H["school"] and not H["farm"] else A0["farmSchool"] if H["farm"] else A0["noSchool"]
        for a in lib["sets"][sname]["active"]:
            if a["kind"] in ks:
                put(a["id"], base + ks[a["kind"]] + tier_pen(a))
    for c in lib["combos"]["active"]:
        if school_ok(H, c) and c["kind"] in ks and (not H["support"] or dmg_free(c)):
            put(c["id"], A0["combo"] + (A0["two"] if c["two"] else 0) + ks[c["kind"]]
                + (A0["noSchool"] if c["set"] != H["school"] else 0) + (A0["farmSchool"] if H["farm"] else 0))
    if pref:
        for i, aid in enumerate(pref):
            if aid in opts and slot_of(by_id[aid]) == "act":
                opts[aid] += A0["hand0"] if i == 0 else A0["hand"]
    return opts


