def universal(t):
    """Эффект, которым пользуется весь отряд: дебафф или контроль на враге, лечение, щит, аура отряда."""
    return t.startswith("st:") or t in ("ctrl", "heal", "shield", "party")


def link_level(TG, H, act0, trait, ng, nt):
    """Связана ли пассивка или реакция как черта героя с доблести 0: (уровень, почему). 3 — с активкой доблести 0, 2 — с соседями
    по циклу, 1 — по роли героя, 0 — не связана. ng и nt — что кладут и чем пользуются соседи по циклу."""
    spec = TG[trait].get("link")
    if not spec:
        return 0, ""
    A = TG[act0]
    ag, at = set(A["give"]), set(A["take"])
    gate = spec.get("gate")
    if gate and not any(r in H["roles"] for r in gate):
        return 0, ""   # черта другой роли: реакции на удар — танку, прибавки к удару — бойцу, фарм-пассивка — фарм-герою
    reqs = []   # условия черты: у каждого — уровень; связка — слабейшее из условий
    own, any_, give = spec.get("own", []), spec.get("any", []), spec.get("give", [])
    if own:
        reqs.append((3 if all(t in ag for t in own) else 0, "own"))
    if any_:
        reqs.append((3 if all(t in ag for t in any_) else 2 if all(t in ag or t in ng for t in any_) else 0, "any"))
    if spec.get("crit"):   # крит — дело физического бойца: шанс крита — от ловкости (§3.2)
        reqs.append(((3 if "hit" in ag else 2) if "phys" in H["roles"] else 0, "crit"))
    if spec.get("kill"):
        reqs.append((3 if "hit" in ag else 2 if "dps" in H["roles"] else 0, "kill"))
    if give:
        reqs.append((3 if any(t in at or t in ag for t in give) else 2 if any(t in nt for t in give) or any(universal(t) for t in give) else 0, "give"))
    lvl = min(x for x, _ in reqs) if reqs else 0
    if lvl:
        return lvl, {3: "с активкой", 2: "с соседями"}[lvl]
    return (1, "роль героя") if gate else (0, "")


def gives_takes(TG, ids):
    g, t = set(), set()
    for aid in ids:
        g.update(TG[aid]["give"])
        t.update(TG[aid]["take"])
    return g, t


def neighbours(per):
    """per: {id героя: (что кладёт, чем пользуется)} по одному циклу → {id: (кладут соседи, пользуются соседи)}."""
    cg, ct = Counter(), Counter()
    for g, t in per.values():
        cg.update(g)
        ct.update(t)
    out = {}
    for hid, (g, t) in per.items():
        out[hid] = ({x for x, n in cg.items() if n - (x in g) > 0}, {x for x, n in ct.items() if n - (x in t) > 0})
    return out


