def tiers_of(kind, entries):
    """Все ступени вида в очереди класса — в порядке предпочтения."""
    out = []
    for k, prefs in entries:
        if k == kind:
            out += [t for t in prefs if t not in out]
    return out


def class_entries(H):
    """Работа класса: главная, второго класса сборного героя, затем круг видов главного класса."""
    main = CLASS[H["classes"][0]]
    return [main["first"]] + [CLASS[c]["first"] for c in H["classes"][1:2] if c in CLASS] + list(main["pool"])


def farm_pool(H):
    return [e for e in FARM_SCHOOL_POOL if not (H["support"] and e[0] in DMG_KINDS)]


def act0_kinds(H):
    """Виды активки доблести 0 по классу: {вид: штраф} — главная работа класса дешевле; у сборного — ещё работа второго класса."""
    out = {}
    if H["farm"]:
        return {k: 3 * i for i, (k, _) in enumerate(farm_pool(H))}
    for ci, c in enumerate(H["classes"][:2]):
        if c == FARM_CLASS:
            continue
        for ki, k in enumerate(CLASS[c]["act0"]):
            pen = 3 * ki + 2 * ci
            if k not in out or pen < out[k]:
                out[k] = pen
    if H["support"]:
        out = {k: p for k, p in out.items() if k not in DMG_KINDS}
    return out


# Цена активки доблести 0 (меньше — лучше): своя школа дешевле приёма «Без школы», обычная активка — сочетания, главная работа класса —
