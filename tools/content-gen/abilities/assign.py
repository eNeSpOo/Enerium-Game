class Rest:
    """Ульта и записи доблестей 1…M−1 героя: из ручного набора, пока законы позволяют, остальное — автомат по плану мест MID.
    taken — активные и ульты героев его сетов: автомат берёт их, только если других вариантов нет."""

    def __init__(self, lib, by_id, by_name, TG, H, a0, tr, pref, taken):
        self.lib, self.by_id, self.by_name, self.TG, self.H = lib, by_id, by_name, TG, H
        self.used, self.seed, self.taken_acts, self.taken_ults = {a0, tr}, seed_of(H["id"]), taken[0], taken[1]
        self.a0, self.tr, self.pref = a0, tr, pref or []
        self.schools = list(dict.fromkeys([H["school"], NO_SCHOOL]))
        self.kit = [a0, tr]

    # --- что кладёт и чем пользуется набор: для выбора записей, которые с ним работают
    def gt(self):
        return gives_takes(self.TG, self.kit)

    def free(self, aid):
        return aid not in self.used and entry_ok(self.H, self.by_id[aid])

    def take(self, aid):
        self.used.add(aid)
        self.kit.append(aid)
        return aid

    def ult(self):
        H = self.H
        if self.pref and self.pref[-1] not in self.used and self.by_id[self.pref[-1]].get("ult") and entry_ok(H, self.by_id[self.pref[-1]]):
            return self.pref[-1]
        if H["farm"]:
            cands = [x["id"] for x in self.lib["farm"]["ult"]]
        else:
            kinds = [k for k in CLASS[H["classes"][0]]["ult"] if not (H["support"] and k in DMG_KINDS)]
            cands = [f"{H['school']}.ult.{k}" for k in kinds]
        cands = [c for c in rot(cands, (self.seed >> 8) & 0xFF) if c in self.by_id and c not in self.used]
        return next((c for c in cands if c not in self.taken_ults), cands[0] if cands else None)

    def acts(self, kinds=None, schools=None):
        """Активные в порядке предпочтения: круг видов класса со сдвигом по сиду, ступени — по классу, своя школа, затем «Без школы»."""
        H = self.H
        ent = farm_pool(H) if H["farm"] else class_entries(H)
        order = []
        for k, _ in rot(ent[1:], self.seed & 0xFF) if len(ent) > 1 else []:
            if k not in order:
                order.append(k)
        order = ([ent[0][0]] if ent else []) + [k for k in order if k != (ent[0][0] if ent else None)]
        out = []
        for sname in schools or self.schools:
            for k in order:
                if kinds is not None and k not in kinds:
                    continue
                for t in (tiers_of(k, ent) or list(L.TIERS)) + [t for t in L.TIERS if t not in tiers_of(k, ent)]:
                    aid = f"{sname}.{k}.{t}"
                    if aid in self.by_id and aid not in out:
                        out.append(aid)
        return out

    def first_free(self, cands):
        cands = [c for c in cands if self.free(c)]
        return next((c for c in cands if c not in self.taken_acts), cands[0] if cands else None)

    def pick_act(self):
        if self.H["farm"]:
            return self.first_free(rot([x["id"] for x in self.lib["farm"]["active"]], self.seed)) or self.pick_school()
        return self.first_free(self.acts()) or self.first_free([x["id"] for s in self.schools for x in self.lib["sets"][s]["active"]])

    def pick_school(self):
        """Фарм-герою — приём «Без школы»."""
        return self.first_free(self.acts(schools=[NO_SCHOOL])) or self.first_free([x["id"] for x in self.lib["sets"][NO_SCHOOL]["active"]])

    def other_role(self, aid):
        return bool(set(self.TG[aid]["roles"]) - set(self.H["own"]))

    def pick_combo(self):
        g, t = self.gt()
        cands = [c["id"] for c in self.lib["combos"]["active"] if self.free(c["id"])]
        if not cands:
            return None

        def score(cid):
            T = self.TG[cid]
            return (-(len(set(T["take"]) & g) + len(set(T["give"]) & t)), self.by_id[cid]["set"] != self.H["school"],
                    cid in self.taken_acts, jitter(self.H["id"], cid, 97))
        return sorted(cands, key=score)[0]

    def pick_mix(self):
        """Запись другой роли или сочетание (Н6 для максимума 2–3): по сиду — сочетание или активная не своей роли."""
        act = self.first_free([a for a in self.acts() if self.other_role(a)]
                              + [x["id"] for s in self.schools for x in self.lib["sets"][s]["active"] if self.other_role(x["id"])])
        combo = self.pick_combo()
        if combo and (not act or (self.seed >> 4) % 2):
            return combo
        return act or combo

    def pick_pr(self, part, role_keys, key):
        """Пассивка или реакция: первой — та, что работает с набором (её условие кладёт сам набор), затем подходящая роли, затем любая."""
        H = self.H
        if H["farm"] and part == "passive":
            cands = [x for x in self.lib["farm"]["passive"]]
        else:
            cands = [x for s in self.schools for x in self.lib["sets"][s][part]]
        cands = [x for x in cands if self.free(x["id"])]
        if not cands:
            return None
        g, _ = self.gt()

        def score(x):
            spec = self.TG[x["id"]].get("link") or {}
            need = spec.get("own", []) + spec.get("any", [])
            works = bool(need) and all(t in g for t in need)
            return (not works, x.get(key) not in role_keys, x["set"] != H["school"] and x["set"] != "Фарм", jitter(H["id"], x["id"], 97))
        return sorted(cands, key=score)[0]["id"]

    def pick(self, slot):
        role = "heal" if self.H["farm"] else CLASS[self.H["classes"][0]]["role"]
        return {"act": self.pick_act, "school": self.pick_school, "combo": lambda: self.pick_combo() or self.pick_act(),
                "mix": lambda: self.pick_mix() or self.pick_act(),
                "pas": lambda: self.pick_pr("passive", PAS_ROLE.get(role, set()), "pas") or self.pick_act(),
                "react": lambda: self.pick_pr("reaction", REACT_ROLE.get(role, set()), "trig") or self.pick_act()}[slot]()

    def mixed(self, ids):
        return any(self.by_id[x].get("combo") or self.other_role(x) for x in ids)

    def build(self):
        H, M = self.H, self.H["maxV"]
        ult = self.ult()
        assert ult, (H["id"], "нет ульты: библиотеке не хватает способностей")
        self.used.add(ult)
        n = M - 1
        ult2 = self.by_name.get(ULT_COMBO.get(H["id"], ""))
        if ult2:
            assert M >= ULT2_FROM and school_ok(H, self.by_id[ult2]), (H["id"], "ульта-сочетание: максимум доблести от 4 и школа героя")
            self.used.add(ult2)
            n -= 1
        mid = []
        for aid in self.pref[:-1]:   # ручной набор — по порядку, без занятого и без того, что закон не пускает
            if len(mid) >= n:
                break
            if aid in self.by_id and not self.by_id[aid].get("ult") and self.free(aid):
                mid.append(self.take(aid))
        plan = (MID_FARM if H["farm"] else MID).get(M, [])
        while len(mid) < n:
            aid = self.pick(plan[len(mid)])
            assert aid, (H["id"], plan[len(mid)], "библиотеке не хватает способностей")
            mid.append(self.take(aid))
        # Н6: сочетание — с максимумом от COMBO_FROM, запись другой роли или сочетание — от MIX_FROM. Замена — последней активной
        # между парой и ультой, иначе последней записи; частью сочетания — её саму
        ids = [self.a0, self.tr] + mid + [ult] + ([ult2] if ult2 else [])
        need = "combo" if M >= COMBO_FROM and not any(self.by_id[x].get("combo") for x in ids) else \
               "mix" if M >= MIX_FROM and not self.mixed(ids) else None
        if need and mid:
            new = self.pick_combo() if need == "combo" else self.pick_mix()
            assert new, (H["id"], "Н6: нет подходящего сочетания или записи другой роли")
            parts = self.by_id[new].get("parts", [])
            at = next((i for i, x in enumerate(mid) if x in parts), None)
            if at is None:
                at = next((i for i in range(len(mid) - 1, -1, -1) if slot_of(self.by_id[mid[i]]) == "act"), len(mid) - 1)
            mid[at] = new
            self.used.add(new)
        if ult2:
            mid.append(ult2)
        return mid, ult


