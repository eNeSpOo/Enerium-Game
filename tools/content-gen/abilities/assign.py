def rot(xs, k):
    xs = list(xs)
    if not xs:
        return xs
    k %= len(xs)
    return xs[k:] + xs[:k]


def slot_of(a):
    """Место способности в наборе — по записи библиотеки."""
    if a.get("ult"):
        return "ult"
    return {"passive": "pas", "farmPassive": "pas", "reaction": "react"}.get(a["kind"], "act")


def sig(kit):
    return tuple(aid for _, _, aid in kit)


def act0_of(kit):
    return next((aid for v, s, aid in kit if v == 0 and s == "act"), None)


def trait_of(kit):
    return next((aid for v, s, aid in kit if v == 0 and s in ("pas", "react")), None)


def dmg_free(a):
    """Запись без урона — для донатного героя поддержки (ADR-0021): ни сама, ни вторая часть сочетания — не урон и не урон по времени."""
    return a["kind"] not in DMG_KINDS and not (a.get("also") and a["also"]["kind"] in DMG_KINDS)


def school_ok(H, a, trait=False):
    """Н5: активки и ульты — своей школы; приёмы «Без школы» — любому; сочетание — школы первой части, двух стихий — только сборным
    источникам; фарм — фарм-герою; черта — любой школы (связку проверяет Н3)."""
    s = a["set"]
    if a.get("combo"):
        return s in (H["school"], NO_SCHOOL) and not (a["two"] and H["src"] not in L.COMBO_TWO_SRC)
    if s == "Фарм":
        return H["farm"]
    return s in (H["school"], NO_SCHOOL) or trait


def entry_ok(H, a):
    """Запись годится герою на доблестях 1 и дальше: школа и запрет урона у донатной поддержки."""
    return school_ok(H, a) and not (H["support"] and slot_of(a) in ("act", "ult") and not dmg_free(a))


def kit_of_names(H, names, by_id, by_name):
    """Набор из имён способностей: [активка, черта, доблести 1…, ульта] → [(доблесть, место, id)]."""
    assert len(names) == H["maxV"] + 2, (H["id"], f"способностей {len(names)}, а максимум доблести + 2 — {H['maxV'] + 2}")
    out = []
    for i, n in enumerate(names):
        assert n in by_name, (H["id"], f"способности «{n}» нет в библиотеке")
        aid = by_name[n]
        out.append((0 if i < 2 else i - 1, slot_of(by_id[aid]), aid))
    return out


