def craft_day(c, L_h, budget, cr):
    """КрафБоссы дня цикла силы c: (души, очки, убийств, атак, раундов — всё × 1000). Души — атаки «своего» отряда дня × цена атаки; не убить —
    не зовёт. Душ Эхо дня не хватает — сколько хватит."""
    cost = pts = kills = att = rounds = 0
    for t, k in cr:
        a = attacks_x100(t, ratio(L_h, c, step_of(t)), c)
        if a is None or not k:
            continue
        cost += k * (a * price(t, c) // 100)
        pts += k * summon_points(t, c)
        kills += k
        att += k * a // 100
        rounds += k * a * ROUNDS[t] // 100
    B = budget * 1000
    if cost > B:
        f = B * 1000 // cost
        return B, pts * f // 1000, kills * f // 1000, att * f // 1000, rounds * f // 1000
    return cost, pts, kills, att, rounds


def ladder_week(week_days, c, n=1, base=ROUND_SOULS, w=PICK_W, cr=()):
    """Неделя Эхо: КрафБоссы дня (cr — craft_day), затем лестница с нуля (§17.4) на остаток душ дня — ECHO_SHARE_BP дохода. Ожидания —
    средние по сидам призыва. Возвращает вершину недели (последняя ступень, после которой лестница выросла; 14 — пал Убер), и итоги × 1000;
    craft и craftKills — очки и победы КрафБоссов (в pts они уже есть); атаки, раунды и победы — все цели Эхо, КрафБоссы тоже."""
    state, done = 1, 0
    tot = dict.fromkeys(('souls', 'pts', 'att', 'rounds', 'kills', 'uber', 'many', 'biome', 'craft', 'craftKills', 'summons'), 0)
    cache = {}
    for souls, L_h in week_days:
        budget = day = echo_souls(souls)
        if cr:
            cs, cp, ck, ca, crn = craft_day(c, L_h, budget, cr)
            tot['souls'] += cs
            tot['pts'] += cp
            tot['craft'] += cp
            tot['craftKills'] += ck
            tot['kills'] += ck
            tot['att'] += ca
            tot['rounds'] += crn
            budget -= cs // 1000
        info = [None] + [step_info(c, s, L_h, budget, base) for s in range(1, MANY)]
        # найденного Многоликого бьют первым — на запас душ Эхо за сутки целиком (ответ автора 01.10.2026, ADR-0039): он вершина и живёт сутки
        info.append(step_info(c, MANY, L_h, day, base))
        if not any(info[1:]):   # отряд дня не убьёт ни одной цели — игрок не зовёт: призыв ради цели, которую не взять, — души впустую
            continue
        b1 = info[1]
        for s in range(2, MANY + 1):   # невыгодные цели игрок не бьёт: они дешевле очками на душу, чем первая ступень
            x = info[s]
            if b1 and x and (x['pts'] + x['biome']) * b1['cost'] * BP < b1['pts'] * x['cost'] * WORTH_BP:
                info[s] = None
        B = budget * 1000
        while B > 0:
            key = (state, L_h, budget)
            if key not in cache:
                cache[key] = per_summon(state, info, n, w)
            up, x = cache[key]
            if state <= UBER and up:
                need = 10 ** 12 // up - done          # призывов × 1000 до подъёма
                cost = need * x['cost'] // 1000
                if cost <= B:
                    B -= cost
                    for k in ('pts', 'att', 'rounds', 'kills', 'uber', 'many', 'biome'):
                        tot[k] += need * x[k] // 1000
                    tot['summons'] += need
                    tot['souls'] += cost
                    state, done = state + 1, 0
                    continue
            k = B * 1000 // x['cost']
            if state <= UBER and up:
                done += k
            for key2 in ('pts', 'att', 'rounds', 'kills', 'uber', 'many', 'biome'):
                tot[key2] += k * x[key2] // 1000
            tot['summons'] += k
            tot['souls'] += B
            B = 0
    return min(state - 1, UBER), done, tot


_WEEKS = {}


def week_results(prof, c, n=1, base=ROUND_SOULS, w=PICK_W, sample=None):
    """Недели цикла c у профиля: КрафБоссы своего цикла и лестница. sample — только эти номера недель (n = 3 дорого считать на годовых
    циклах: таблицы берут выборку)."""
    key = (prof, c, n, base, w, tuple(sample) if sample else None)
    if key not in _WEEKS:
        ws = weeks(prof, c)
        idx = [i for i in sample if i < len(ws)] if sample else range(len(ws))
        cr = crafts(prof, c)
        _WEEKS[key] = [ladder_week(ws[i], c, n, base, w, cr) for i in idx]
    return _WEEKS[key]


def avg_week_points(prof, c):
    res = week_results(prof, c)
    return sum(t['pts'] for _, _, t in res) // (1000 * len(res))


def nice(v):
    """Порог планки: вниз до двух значащих цифр."""
    if v < 100:
        return max(1, v)
    k = 10 ** (len(str(v)) - PLANK_DIGITS)
    return v // k * k


def median_week(prof, c):
    """Типичная неделя профиля в цикле c — медиана очков недель."""
    return median([t['pts'] // 1000 for _, _, t in week_results(prof, c)])


def retention_week(c):
    """Удержание §17.6: очки увлечённого в среднем за первые RET_WEEKS недель цикла c."""
    res = week_results('увлечённый', c)[:RET_WEEKS]
    return sum(t['pts'] // 1000 for _, _, t in res) // len(res)


def plank1(c):
    """Первая планка цикла: типичная неделя обычного — PLANK_R / 100 первых планок, одна мерка на все циклы (ADR-0042, ADR-0043). Законы —
    обычный на PLANK_REG-й, увлечённый на PLANK_ENG-й, в цикле II обычный берёт первую в 1-ю неделю (ADR-0031, п. 8), удержание — в goals."""
    return nice(median_week('обычный', c) * 100 // PLANK_R)


def plank_of(pts, p1):
    k = 0
    while k < PLANKS and pts >= p1 * PLANK_MUL ** k:
        k += 1
    return k


