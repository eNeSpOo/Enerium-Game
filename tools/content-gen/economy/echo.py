# --- лестница за неделю: ожидания, целочисленно ---

def step_info(c, s, L_h, budget, base):
    """Ступень для отряда дня: атак, душ на убийство, очков — × 1000; None — не убить или не успеть за срок цели на бюджет дня.
    У Многоликого ещё очки его биома за одну попытку отряда этого дня."""
    t = type_of(s)
    a = attacks_x100(t, ratio(L_h, c, s), c)
    if a is None:
        return None
    cost = a * price(t, c, base) * 10
    if cost * DAY_H > budget * 1000 * life_h(t):
        return None
    return {'att': a * 10, 'rounds': a * 10 * ROUNDS[t], 'cost': cost, 'pts': points(c, s) * 1000,
            'biome': many_points(c, L_h) * 1000 if s == MANY else 0}


def offer_probs(pool, n, w=PICK_W):
    """Предложения лестницы: n разных открытых ступеней из pool по весам w, нормированным между собой, без повторов.
    Список (набор, вероятность × 10^9)."""
    out, W = [], {j: w[j - 1] for j in pool}

    def rec(chosen, left, p):
        if len(chosen) == n or not left:
            out.append((chosen, p))
            return
        w = sum(W[j] for j in left)
        for j in left:
            rec(chosen + [j], [x for x in left if x != j], p * W[j] // w)
    rec([], list(pool), 10 ** 9)
    return out


def per_summon(state, info, n, w=PICK_W):
    """Ожидания одного призыва. Открыты ступени 1..min(state, 14); state 15 — Убер уже пал. Лестница растёт после победы
    над сильнейшим открытым (§17.4). Многоликий — сверх лестницы: с шансом MANY_SUMMON_BP призыв приносит его, и игрок берёт его.
    Иначе — предложение лестницы: игрок берёт вершину, если она в предложении и по силам, иначе — старшую по силам.
    Возвращает вероятность подняться (× 10^9) и ожидания на призыв (× 1000): души, очки, атаки, убийства, Уберы, очки биомов
    Многоликого; Многоликие — × 10^6: он редок."""
    top = min(state, UBER)
    up, acc = 0, dict.fromkeys(('cost', 'pts', 'att', 'rounds', 'kills', 'uber', 'many', 'biome'), 0)   # суммы p × величина
    acc['cost'] += 10 ** 9 * SUMMON_SOULS * 1000
    pm = 10 ** 9 * MANY_SUMMON_BP // BP

    def take(p, x):
        for k in ('cost', 'pts', 'att', 'rounds', 'biome'):
            acc[k] += p * x[k]
        acc['kills'] += p * 1000
    if info[MANY]:
        take(pm, info[MANY])
        acc['many'] += pm * 10 ** 6
    for offer, p in offer_probs(range(1, top + 1), n, w):
        p = p * (10 ** 9 - pm) // 10 ** 9
        ok = [j for j in offer if info[j]]
        if not ok:
            continue
        pick = top if (state <= UBER and top in ok) else max(ok)
        if pick == state:
            up += p
        take(p, info[pick])
        if pick == UBER:
            acc['uber'] += p * 1000
    return up, {k: v // 10 ** 9 for k, v in acc.items()}


def summon_points(t, pc):
    """Очки КрафБосса типа t цикла силы pc по общей лестнице (ADR-0043): очки на душу ступени лестницы недели его уровня (STEP_OF) в цикле
    его силы × души его убийства «своим» отрядом (DESIGN × раунды типа; цена раунда цикла сокращается). Ниже II — как II, за VI — ×
    POINTS_CYCLE_MUL за цикл. Цикла игрока здесь нет: его очки не умножает цикл."""
    c = max(FIRST, min(pc, CYCLES[-1]))
    s = STEP_OF[t]
    ts = type_of(s)
    return points(c, s) * pts_design(t) * ROUNDS[t] // (pts_design(ts) * ROUNDS[ts]) * POINTS_CYCLE_MUL ** max(0, pc - CYCLES[-1])


def common_ladder(pc):
    """Общая лестница врагов Эхо цикла силы pc: ступени 1–15 лестницы недели и КрафБоссы четырёх типов — от слабого к сильному: по уровню
    (ступень, на которой стоит враг), затем по душам убийства «своим» отрядом. [(ключ, имя, ступень уровня, душ на убийство, очки)]."""
    c = max(FIRST, min(pc, CYCLES[-1]))
    rows = [(f's{s}', f'ступень {s} · {TYPE_NAME[type_of(s)].lower()}', s, DESIGN[type_of(s)] * price(type_of(s), c), points(c, s))
            for s in range(1, MANY + 1)]
    rows += [(t, f'{SUMMON_NAME[t]} · {SUMMON_KINDS[t]}', STEP_OF[t], DESIGN[t] * price(t, c), summon_points(t, c)) for t in SUMMON]
    return sorted(rows, key=lambda r: (r[2], r[3], r[0]))


