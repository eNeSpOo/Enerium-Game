def interp(rows, x):
    """Линейная интерполяция по таблице [(x, y)], целочисленно; за краями — крайние значения."""
    if x <= rows[0][0]:
        return rows[0][1]
    for (x0, y0), (x1, y1) in zip(rows, rows[1:]):
        if x <= x1:
            return y0 + (y1 - y0) * (x - x0) // (x1 - x0)
    return rows[-1][1]


