def round_price(c, base=ROUND_SOULS):
    """Цена раунда атаки в цикле c: растёт как доход душ обычного — средний день цикла к среднему дню цикла II (ADR-0043); цикл I —
    × номер первого биома цикла (ADR-0011) × число забегов (ADR-0014). Округление до целого."""
    if c in CYCLES:
        num, den = base * day_souls(c), day_souls(FIRST)
    else:
        num, den = base * soul_scale(c), soul_scale(FIRST)
    return max(1, (2 * num + den) // (2 * den))


def price(t, c, base=ROUND_SOULS):
    return ROUNDS[t] * round_price(c, base)


def growth(s, g=POINTS_GROWTH_BP):
    """Множитель ступени s к первой, б. п.: g в степени s − 1, целочисленно по шагам."""
    v = BP
    for _ in range(s - 1):
        v = v * g // BP
    return v


