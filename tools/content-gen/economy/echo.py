def goals():
    """Цели Эхо по ADR-0031, п. 8, и правило ×1,7 — строки: (что, цель, итог, выполнено)."""
    out = []
    f = FIRST
    for i in (0, 1):                        # 1-я и средняя неделя цикла (у цикла II две полные недели)
        for t, days_max, what in [('b', 1, 'Босс недели')] + [(t, SUMMON_DAYS[t], f'Призванный: {SUMMON_NAME[t].lower()} ({SUMMON_KINDS[t]})') for t in SUMMON]:
            c = summon_cycle(t) if t in SUMMON else f
            w = weeks('обычный', c)[i]
            souls, L_h = w[len(w) // 2]
            a = attacks_x100(t, ratio(L_h, c, step_of(t)), c)
            day = echo_souls(souls)
            need = None if a is None else a * price(t, c) // 100
            got = 'не убить' if need is None else f'{fmt(need)} душ при {fmt(day)} в день — {dec1(need, day)} дн.'
            out.append((f'{what}: обычный, цикл {ROMAN[c - 1]}, {i + 1}-я неделя', f'не дороже {days_max} дн. душ Эхо', got,
                        need is not None and need <= day * days_max))
    # сильнее тип — дороже убийство (ADR-0039): в одном цикле силы босс недели ≤ призванный босс ≤ Убер ≤ Забытый — души на убийство
    # «своим» отрядом цикла (обычный, 1-я неделя; циклы IV–VI — по образцу III)
    chain = ['b', 'sb', 'su', 'sf']
    for c in CYCLES:
        need, here = {}, [t for t in chain if t not in SUMMON or summon_cycle(t) <= c]   # тип, которого в этом цикле силы ещё нет, не сравниваем
        for t in here:
            w = weeks('обычный', c)[0]
            a = attacks_x100(t, ratio(w[len(w) // 2][1], c, step_of(t)), c)
            need[t] = None if a is None else a * price(t, c) // 100
        ok = all(need[t] is not None for t in here) and all(need[a] <= need[b] for a, b in zip(here, here[1:]))
        out.append((f'Сильнее тип — дороже убийство, цикл {ROMAN[c - 1]}', 'босс недели ≤ призванные босс ≤ Убер ≤ Забытый, души обычного',
                    ' ≤ '.join(f'{TYPE_NAME[t].lower()} {"не убить" if need[t] is None else fmt(need[t])}' for t in here), ok))
    # Многоликий сильнее 14-й ступени (слово автора 01.10.2026): выше уровнем и дороже убийство тем же отрядом, что берёт Убера за DESIGN атак
    for c in CYCLES:
        L = foe_L(c, UBER) * ON_LEVEL // 100
        au, am = attacks_x100('u', ratio(L, c, UBER), c), attacks_x100('m', ratio(L, c, MANY), c)
        su = None if au is None else au * price('u', c) // 100
        sm = None if am is None else am * price('m', c) // 100
        good = foe_L(c, MANY) > foe_L(c, UBER) and su is not None and (sm is None or sm > su)
        out.append((f'Многоликий сильнее Убера, цикл {ROMAN[c - 1]}', 'выше уровнем и дороже убийство тем же отрядом',
                    f'уровень {foe_lvl(c, MANY)} против {foe_lvl(c, UBER)}; душ {"не убить" if sm is None else fmt(sm)} против {fmt(su or 0)}', good))
    eng = [t['uber'] for _, _, t in week_results('увлечённый', f)]
    out.append((f'Убер-босс у увлечённого — с цикла {ROMAN[f - 1]}', 'ADR-0030, п. 7',
                'Уберов по неделям: ' + ' / '.join(dec1(u, 1000) for u in eng), any(eng)))
    for n in OFFERS:
        first = next(((c, i) for c in CYCLES for i, (_, _, t) in enumerate(week_results('обычный', c, n)) if t['uber'] >= 1000), None)
        tops = ' / '.join(str(top) for c in CYCLES if c <= TEMPLATE for top, _, _ in week_results('обычный', c, n))
        got = (f'с цикла {ROMAN[first[0] - 1]}, {first[1] + 1}-я неделя' if first else 'в неделю не падает: вершины недель циклов II–III — ' + tops)
        out.append((f'Убер-босс у обычного, вариантов призыва {n}', 'позже, чем у увлечённого', got, not first or first > (f, 1)))
    p1, w1 = plank1(f), week_results('обычный', f)[0][2]['pts'] // 1000
    out.append((f'Первая планка цикла {ROMAN[f - 1]} — {fmt(p1)}', 'обычный берёт её в 1-ю неделю', f'очков 1-й недели — {fmt(w1)}', w1 >= p1))
    for c in CYCLES:
        reg = sum(t['pts'] for _, _, t in week_results('обычный', c))
        pay = sum(t['pts'] for _, _, t in week_results(PAYER, c))
        out.append((f'×1,7: плательщик, цикл {ROMAN[c - 1]}', f'очки Эхо не больше ×{dec1(PAYER_MAX_X10, 10)} к обычному',
                    f'{mult(pay, reg)} (души {mult(E.payer_worst_x100(min(c, TEMPLATE)), 100)})', pay * 10 <= reg * PAYER_MAX_X10))
    return out


