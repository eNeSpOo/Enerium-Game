# --- лестница за неделю: ожидания, целочисленно ---

def step_info(c, s, L_h, budget, base):
    """Ступень для отряда дня: атак, душ на убийство, очков — × 1000; None — не убить или не успеть за срок цели на бюджет дня.
    У Многоликого ещё очки его биома за одну попытку отряда этого дня."""
    t = type_of(s)
    a = attacks_x100(t, ratio(L_h, c, s), c)
    if a is None:
        return None
    cost = a * price(t, c, base) * 10
    if cost * DAY_H > budget * 1000 * life_h(t):
        return None
    return {'att': a * 10, 'cost': cost, 'pts': points(c, s) * 1000, 'biome': many_points(c, L_h) * 1000 if s == MANY else 0}


def offer_probs(pool, n, w=PICK_W):
    """Предложения лестницы: n разных открытых ступеней из pool по весам w, нормированным между собой, без повторов.
    Список (набор, вероятность × 10^9)."""
    out, W = [], {j: w[j - 1] for j in pool}

    def rec(chosen, left, p):
        if len(chosen) == n or not left:
            out.append((chosen, p))
            return
        w = sum(W[j] for j in left)
        for j in left:
            rec(chosen + [j], [x for x in left if x != j], p * W[j] // w)
    rec([], list(pool), 10 ** 9)
    return out


def per_summon(state, info, n, w=PICK_W):
    """Ожидания одного призыва. Открыты ступени 1..min(state, 14); state 15 — Убер уже пал. Лестница растёт после победы
    над сильнейшим открытым (§17.4). Многоликий — сверх лестницы: с шансом MANY_SUMMON_BP призыв приносит его, и игрок берёт его.
    Иначе — предложение лестницы: игрок берёт вершину, если она в предложении и по силам, иначе — старшую по силам.
    Возвращает вероятность подняться (× 10^9) и ожидания на призыв (× 1000): души, очки, атаки, убийства, Уберы, очки биомов
    Многоликого; Многоликие — × 10^6: он редок."""
    top = min(state, UBER)
    up, acc = 0, dict.fromkeys(('cost', 'pts', 'att', 'kills', 'uber', 'many', 'biome'), 0)   # суммы p × величина
    acc['cost'] += 10 ** 9 * SUMMON_SOULS * 1000
    pm = 10 ** 9 * MANY_SUMMON_BP // BP

    def take(p, x):
        for k in ('cost', 'pts', 'att', 'biome'):
            acc[k] += p * x[k]
        acc['kills'] += p * 1000
    if info[MANY]:
        take(pm, info[MANY])
        acc['many'] += pm * 10 ** 6
    for offer, p in offer_probs(range(1, top + 1), n, w):
        p = p * (10 ** 9 - pm) // 10 ** 9
        ok = [j for j in offer if info[j]]
        if not ok:
            continue
        pick = top if (state <= UBER and top in ok) else max(ok)
        if pick == state:
            up += p
        take(p, info[pick])
        if pick == UBER:
            acc['uber'] += p * 1000
    return up, {k: v // 10 ** 9 for k, v in acc.items()}


def ladder_week(week_days, c, n=1, base=ROUND_SOULS, w=PICK_W):
    """Неделя Эхо: лестница с нуля (§17.4), души дня — ECHO_SHARE_BP дохода. Ожидания — средние по сидам призыва.
    Возвращает вершину недели (последняя ступень, после которой лестница выросла; 14 — пал Убер), и итоги × 1000."""
    state, done = 1, 0
    tot = dict.fromkeys(('souls', 'pts', 'att', 'kills', 'uber', 'many', 'biome'), 0)
    cache = {}
    for souls, L_h in week_days:
        budget = echo_souls(souls)
        info = [None] + [step_info(c, s, L_h, budget, base) for s in range(1, MANY + 1)]
        b1 = info[1]
        for s in range(2, MANY + 1):   # невыгодные цели игрок не бьёт: они дешевле очками на душу, чем первая ступень
            x = info[s]
            if b1 and x and (x['pts'] + x['biome']) * b1['cost'] * BP < b1['pts'] * x['cost'] * WORTH_BP:
                info[s] = None
        B = budget * 1000
        while B > 0:
            key = (state, L_h, budget)
            if key not in cache:
                cache[key] = per_summon(state, info, n, w)
            up, x = cache[key]
            if state <= UBER and up:
                need = 10 ** 12 // up - done          # призывов × 1000 до подъёма
                cost = need * x['cost'] // 1000
                if cost <= B:
                    B -= cost
                    for k in ('pts', 'att', 'kills', 'uber', 'many', 'biome'):
                        tot[k] += need * x[k] // 1000
                    tot['souls'] += cost
                    state, done = state + 1, 0
                    continue
            k = B * 1000 // x['cost']
            if state <= UBER and up:
                done += k
            for key2 in ('pts', 'att', 'kills', 'uber', 'many', 'biome'):
                tot[key2] += k * x[key2] // 1000
            tot['souls'] += B
            B = 0
    return min(state - 1, UBER), done, tot


_WEEKS = {}


def week_results(prof, c, n=1, base=ROUND_SOULS, w=PICK_W):
    key = (prof, c, n, base, w)
    if key not in _WEEKS:
        _WEEKS[key] = [ladder_week(wk, c, n, base, w) for wk in weeks(prof, c)]
    return _WEEKS[key]


def avg_week_points(prof, c):
    res = week_results(prof, c)
    return sum(t['pts'] for _, _, t in res) // (1000 * len(res))


def nice(v):
    """Порог планки: вниз до двух значащих цифр."""
    if v < 100:
        return max(1, v)
    k = 10 ** (len(str(v)) - PLANK_DIGITS)
    return v // k * k


def plank1(c):
    """Первая планка цикла. Средняя неделя обычного — на планке PLANK_REG (лутбоксы.md); в первом цикле рейтинга первую планку обычный
    берёт уже в 1-ю неделю (ADR-0031, п. 8). С цикла III ещё удержание §17.6: увлечённый — прообраз среднего места прошлого цикла — в первую
    неделю нового берёт последнюю планку. Порог — меньший из них."""
    reg = avg_week_points('обычный', c) // PLANK_MUL ** (PLANK_REG - 1)
    if c - 1 not in CYCLES:
        return nice(min(reg, week_results('обычный', c)[0][2]['pts'] // 1000))
    arrive = week_results('увлечённый', c)[0][2]['pts'] // 1000 // PLANK_MUL ** (PLANKS - 1)
    return nice(min(reg, arrive))


def plank_of(pts, p1):
    k = 0
    while k < PLANKS and pts >= p1 * PLANK_MUL ** k:
        k += 1
    return k


def many_value(prof, c, i=-1):
    """Биом Многоликого против Лика недели в неделю i цикла: очки биома за одну попытку отрядом середины недели, их цена в душах
    по очкам на душу этой недели, и осколки Лика в душах по осколкам Эхо игрока за неделю (лутбоксы.md).
    Возвращает словарь; души — целые, Многоликих за неделю — × 10^6."""
    w = weeks(prof, c)[i]
    _, _, t = week_results(prof, c)[i]
    souls = sum(echo_souls(s) for s, _ in w)
    L_h = w[len(w) // 2][1]
    r = ratio(L_h, c, UBER)
    pts = many_full(c) * many_share(r) // BP
    week_pts = t['pts'] // 1000
    biome_souls = pts * souls // week_pts
    shards = ECHO_SHARDS_X10[c][[p for p, _ in E.PROFILES].index(prof)]
    craft_souls = lik_shards(c) * souls * 10 // shards
    return {'r': r, 'share': many_share(r), 'pts': pts, 'week_pts': week_pts, 'souls': souls, 'biome_souls': biome_souls,
            'craft_souls': craft_souls, 'k': biome_souls * BP // craft_souls, 'many': t['many'], 'biome_week': t['biome'] // 1000}


