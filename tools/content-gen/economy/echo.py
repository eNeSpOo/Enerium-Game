def interp(rows, x):
    """Линейная интерполяция по таблице [(x, y)], целочисленно; за краями — крайние значения."""
    if x <= rows[0][0]:
        return rows[0][1]
    for (x0, y0), (x1, y1) in zip(rows, rows[1:]):
        if x <= x1:
            return y0 + (y1 - y0) * (x - x0) // (x1 - x0)
    return rows[-1][1]


def dmg_at(t, r):
    """Урон по главному врагу за атаку при отношении r, % его базы. За верхним краем замера — пропорционально отношению: в годовых
    циклах (ADR-0043) отряд обычного перерастает лестницу своего цикла в разы, а замер кончается на SIM_RATIOS[-1]; от 350 к 400 урон
    растёт как отношение (×1,12–1,16 на ×1,14). Прежде урон за краем стоял — и здоровье, и атаки «замерзали» на краю."""
    rows = [(x, a) for x, a, *_ in SIM_DMG[t]]
    if r > rows[-1][0]:
        return rows[-1][1] * r // rows[-1][0]
    return interp(rows, r)


def round_to(v, step):
    return max(step, (v + step // 2) // step * step)


def ref_ratio(t, c):
    """Отношение «своего» отряда цикла c к главному врагу типа t, × 100: главный отряд обычного игрока в середине недели REF_WEEK
    цикла (ADR-0031, п. 8). Отряд — свой у каждого цикла: калькулятор подъёма (cycle/climb-days.json), прежде циклы IV–VI шли «по образцу III»."""
    prof = REF_PROF.get(t, 'обычный')
    if prof is None:
        return ON_LEVEL
    ws = weeks(prof, c)
    w = ws[min(REF_WEEK, len(ws) - 1)]
    return ratio(w[len(w) // 2][1], c, step_of(t))


def sim_cycle(t):
    """Цикл, при здоровье которого меряются атаки на убийство: II, у призванного — первый цикл его силы (цели ADR-0031, п. 8, меряются там)."""
    return summon_cycle(t) if t in SUMMON else FIRST


def hp_design(t, c=None):
    """Здоровье главного врага по замыслу: DESIGN атак «своего» отряда цикла c с запасом, % базы карты — без пола лестницы врагов."""
    c = FIRST if c is None else c
    return round_to(DESIGN[t] * dmg_at(t, ref_ratio(t, c)) * HP_MARGIN_BP // BP, HP_ROUND)


def hp_pct(t, c=None):
    """Здоровье главного врага в цикле c, % базы карты (как BIOMES.bossHpPct): DESIGN атак «своего» отряда цикла с запасом (hp_design),
    но не ниже пола лестницы врагов (HP_FLOOR): старший тип не слабее младшего. Призванный враг — так же по циклу силы (summon.types
    в echo-rules.js), прежде у «крафтового» было одно число на все циклы."""
    c = FIRST if c is None else c
    v = hp_design(t, c)
    if t in HP_FLOOR:
        lo, bp = HP_FLOOR[t]
        v = max(v, round_to(hp_pct(lo, c) * bp // BP, HP_ROUND))
    return v


def many_hp_pct(t, c=None):
    """Главный враг этажа в биоме Многоликого: попытка одна — доля MANY_FLOOR_HP_BP одной атаки «своего» отряда."""
    return round_to(hp_design(t, c) * MANY_FLOOR_HP_BP // (BP * DESIGN[t]), HP_ROUND)   # по замыслу, без пола лестницы: этаж — доля одной атаки


def attacks_x100(t, r, c=None):
    """Атак на убийство главного врага цикла c у отряда с отношением r — замер прогона, × 100; None — не убить.
    Замер шёл при здоровье цикла замера (sim_cycle: II, у призванного — первый цикл его силы); у другого здоровья и за краем отношений
    замера — по связи «здоровье / урон за атаку → атаки» того же замера."""
    hp_sim, rows = SIM_KILL[t]
    ok = [(x, a) for x, a in rows if a is not None]
    if not ok or r < ok[0][0]:                # отряд слабее, чем тот, что в замере убивал: не убить
        return None
    # атаки — функция одного числа: здоровье цели / урон за атаку (ADR-0043). Замер даёт эту связь при здоровье замера; у другого здоровья
    # и за краем отношений замера атаки берутся по ней же. Прежде атаки масштабировались здоровьем линейно, и упор «одна атака» в замере
    # раздувался: в цикле IV «свой» отряд бил бы рядового 3,4 атаки вместо одной
    g = sorted((1000 * hp_sim // dmg_at(t, x), a) for x, a in ok)
    q = 1000 * hp_pct(t, c) // dmg_at(t, r)
    if q <= g[0][0]:
        a = g[0][1] * q // g[0][0]
    elif q >= g[-1][0]:
        a = g[-1][1] * q // g[-1][0]
    else:
        a = next(a0 if x1 == x0 else a0 + (a1 - a0) * (q - x0) // (x1 - x0) for (x0, a0), (x1, a1) in zip(g, g[1:]) if x0 <= q <= x1)
    return max(100, a)


