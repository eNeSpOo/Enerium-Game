/* Ожидание Эло E(d) = 1 / (1 + 10^(d / 400)) для разницы d = 0…cap, в б. п. — без дробей: q = 10^(1/400) — целый корень
   400-й степени с масштабом 10^30 (двоичный поиск), 10^(d/400) — q^d тем же масштабом, E — деление с округлением к ближайшему */
function eloTable(cap, scale) {
  const S = 10n ** 30n, P = BigInt(scale), target = 10n * S ** P;
  let lo = S, hi = 2n * S;
  while (hi - lo > 1n) { const mid = (lo + hi) / 2n; if (mid ** P <= target) lo = mid; else hi = mid; }
  const out = []; let p = S;
  for (let d = 0; d <= cap; d++) { out.push(Number((20000n * S + (S + p)) / (2n * (S + p)))); p = p * lo / S; }
  return out;
}

