/* в разделе «Спуск»: искажённых и нежити во врагах спуска нет до 11-го биома (дайджест) */
const DESCENT_BAN = /искаж|нежит/i;
/* в промтах арта — ни Эуклида, ни спойлеров */
const PROMPT_BAN = /euclid|iridi|eridar|etrion|zarif|the shell|seal of|sixth (?:element|share|part)|firstborn|mother of the world|failed cast/i;

/* каждое слово seen — в своём источнике: иначе список разошёлся с дайджестом, GDD или сводом */
function verify() {
  const out = [];
  const t = read(FILES.digest), i = t.indexOf('## Нельзя показывать раннему игроку');
  if (i < 0) return ['дайджест: нет раздела «Нельзя показывать раннему игроку»'];
  const j = t.indexOf('\n## ', i + 3), digest = t.slice(i, j < 0 ? t.length : j).toLowerCase();
  const gdd = read(FILES.gdd38).toLowerCase(), svod = read(FILES.svod).toLowerCase();
  for (const sp of DIGEST) if (!digest.includes(sp.seen.toLowerCase())) out.push(`спойлер «${sp.seen}»: слова нет в разделе дайджеста — список разошёлся с дайджестом`);
  for (const sp of DEEP) if (!gdd.includes(sp.seen.toLowerCase())) out.push(`спойлер «${sp.seen}»: слова нет в таблице §38 — список разошёлся с GDD`);
  for (const sp of CITY) if (!svod.includes(sp.seen.toLowerCase())) out.push(`тайна города «${sp.seen}»: слова нет в своде — список разошёлся со сводом`);
  return out;
}
/* спойлеры в тексте игрока: [{ hit, why }] */
function scan(text, part) {
  const t = String(text), out = [];
  for (const sp of DIGEST.concat(DEEP, CITY)) { const m = t.match(sp.re); if (m) out.push({ hit: m[0], why: sp.why }); }
  if (part === 'descent') { const m = t.match(DESCENT_BAN); if (m) out.push({ hit: m[0], why: 'искажённые и нежить во врагах спуска — только с 11-го биома' }); }
  if (/этрион/i.test(t) && !/вестник|летописец/i.test(t)) out.push({ hit: 'Этрион', why: 'Этрион — только вестник пятерых и летописец' });
  return out;
}

module.exports = { DIGEST, DEEP, CITY, DESCENT_BAN, PROMPT_BAN, verify, scan };
