const DESCENT_RACES = /искаж|нежит|перворожд/i;

const read = f => fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n');
function digestSection() {
  const t = read(FILES.digest), i = t.indexOf('## Нельзя показывать раннему игроку');
  if (i < 0) return '';
  const j = t.indexOf('\n## ', i + 3);
  return t.slice(i, j < 0 ? t.length : j);
}
/* каждое слово seen — в своём источнике */
function verify() {
  const out = [], src = { digest: digestSection().toLowerCase(), gdd38: read(FILES.gdd38).toLowerCase(), svod: read(FILES.svod).toLowerCase() };
  if (!src.digest) out.push('дайджест: нет раздела «Нельзя показывать раннему игроку»');
  for (const L of LEX) if (!src[L.src].includes(L.seen.toLowerCase())) out.push(`лестница: слова «${L.seen}» нет в источнике «${L.src}» — список разошёлся с источником`);
  if (!src.digest.includes('эуклид, печать, оболочка')) out.push('лестница: в дайджесте нет строки «Эуклид, печать, Оболочка» — сверить список');
  return out;
}
/* все совпадения в тексте: [{ lvl, hit, why, at }] */
function scan(text) {
  const t = String(text == null ? '' : text), out = [];
  for (const L of LEX) { const m = t.match(L.re); if (m) out.push({ lvl: L.lvl, hit: m[0], why: L.why, at: m.index }); }
  /* одно место — одна ступень: «печать богов» (D) не дублирует «печать» (H1) */
  return out.filter(x => !out.some(y => y !== x && y.at <= x.at && x.at < y.at + y.hit.length && FROM[y.lvl] > FROM[x.lvl]));
}
/* можно ли игроку видеть ступень lvl в цикле cyc (1–6); team — текст только для команды. Раскрытие (D) — с цикла VI (ADR-0054) */
const allowed = (lvl, cyc, team) => !!team || cyc >= FROM[lvl];
/* закон лестницы — слова автора числами: с какого цикла ступень слова открыта игроку. Его сверяет check_spoilers.js при каждом прогоне */
const LAW = { H1: 3, H2: 4, H3: 5, D: 6 };
function lawCheck(from) {
  const F = from || FROM, out = [];
  for (const [lvl, c] of Object.entries(LAW)) {
    if (F[lvl] !== c) out.push(`лестница: ступень ${lvl} открыта игроку с цикла ${F[lvl]}, по слову автора — с цикла ${c}`);
    for (let cyc = 1; cyc <= 6; cyc++) if ((cyc >= F[lvl]) !== (cyc >= c)) out.push(`лестница: ступень ${lvl} в цикле ${cyc} — ${cyc >= F[lvl] ? "открыта" : "закрыта"}, а должна быть ${cyc >= c ? "открыта" : "закрыта"}`);
  }
  if (Object.keys(F).length !== Object.keys(LAW).length) out.push("лестница: ступеней не четыре");
  return out;
}
/* нарушения лестницы в тексте */
const violations = (text, cyc, team) => scan(text).filter(h => !allowed(h.lvl, cyc, team));

